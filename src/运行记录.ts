// 运行记录 —— 上一次跑的是「运行」还是「测试」，以及测试标出来的报错
//
// 用户 2026-11-15 定的运行方法三步（原话）：
//   「先看之前运行方法和测试方法哪个最后执行,是测试方法就把测试方法标报错的全标失效
//    再启动开始单元,否则直接启动开始单元」
//
// ⇒ 但测试方法是**不落盘**的（用户 m03542 第②条：「报错不落盘,临时存储」），
//   它标出来的报错只在返回里，下次运行方法读不到 ⇒ 所以要在这里落一份。
//
// 文件放在**项目目录**下，跟蓝图 json 平级：
//   { "上次": "测试" | "运行", "测试报错": [{ 蓝图, 单元, 码, 消息 }] }

import fs from 'node:fs'
import path from 'node:path'

/** 一条测试报错：哪张图的哪个单元、因为哪个检查码 */
export interface 测试报错 {
  蓝图: string
  单元: string
  码: string
  消息: string
}

export interface 运行记录 {
  /** 上一次跑的是哪个 */
  上次: '运行' | '测试'
  /** 上次测试标出来的报错（只在「上次」是测试时有意义） */
  测试报错: 测试报错[]
  /**
   * 这一次运行的标识（用户 m19432：停止请求必须绑定到「某个项目的某一次运行」）。
   *
   * 运行开始时写进去、结束时清掉。停止命令只写「要停这个标识」，
   * 于是上一次留下的停止请求不会把下一次重跑也中止掉。
   */
  本次运行?: string
  /**
   * 有没有人要求「结束」（用户 2026-11-15：「我建议做一个结束命令，供测试和
   * AI 或用户用」）。
   *
   * 跨进程只能靠文件：`结束` 命令写进去，状态机每轮读一次，
   * 读到就清池子、清共享数据、返回「中止」。
   *
   * 值是要停的那一次运行的标识（老数据可能是 `true`，当「不认标识」处理）。
   */
  要求结束?: boolean | string
}

/** 记录文件名 */
export const 运行记录文件名 = '运行记录.json'

/** 空记录 —— 从来没跑过的时候用 */
export function 空运行记录(): 运行记录 {
  return { 上次: '运行', 测试报错: [] }
}

/** 读运行记录；文件不在或坏了都当没有 */
export function 读运行记录(项目目录: string): 运行记录 {
  const 文件 = path.join(项目目录, 运行记录文件名)
  try {
    if (!fs.existsSync(文件)) return 空运行记录()
    const 原始 = JSON.parse(fs.readFileSync(文件, 'utf8')) as Partial<运行记录>
    const 上次 = 原始.上次 === '测试' ? '测试' : '运行'
    const 报错 = Array.isArray(原始.测试报错)
      ? 原始.测试报错
          .filter((x): x is 测试报错 => !!x && typeof x === 'object')
          .map((x) => ({
            蓝图: String(x.蓝图 ?? ''),
            单元: String(x.单元 ?? ''),
            码: String(x.码 ?? ''),
            消息: String(x.消息 ?? ''),
          }))
      : []
    const 要求结束 =
      原始.要求结束 === true
        ? true
        : typeof 原始.要求结束 === 'string' && 原始.要求结束 !== ''
          ? 原始.要求结束
          : undefined
    const 本次运行 = typeof 原始.本次运行 === 'string' && 原始.本次运行 !== '' ? 原始.本次运行 : undefined
    const 记录: 运行记录 = { 上次, 测试报错: 报错 }
    if (本次运行) 记录.本次运行 = 本次运行
    if (要求结束 !== undefined) 记录.要求结束 = 要求结束
    return 记录
  } catch {
    return 空运行记录()
  }
}

/**
 * 这一次运行收到「结束」要求了吗。
 *
 * - 记录了标识的停止请求：只有标识对上才算（上一次的请求不会掐掉这一次重跑）
 * - 老数据的 `true`：认，但没有标识也就没法定向 —— 只在没有本条标识时兜底
 */
export function 应当停止(项目目录: string, 本次运行?: string): boolean {
  const 要 = 读运行记录(项目目录).要求结束
  if (要 === true) return true
  if (本次运行 && 要 === 本次运行) return true
  return false
}

/** 写运行记录 */
export function 写运行记录(项目目录: string, 记录: 运行记录): void {
  const 文件 = path.join(项目目录, 运行记录文件名)
  fs.writeFileSync(文件, JSON.stringify(记录, null, 2) + '\n', 'utf8')
}

/**
 * 造一个运行标识（用户 m19572：启动时就把标识交给调用方，停止时核对它）。
 * 形状：`项目名#时间戳#随机串`
 */
export function 新运行标识(项目名: string): string {
  return `${项目名}#${Date.now()}#${Math.random().toString(36).slice(2, 8)}`
}

/**
 * 这一趟收尾：**只清自己那一次**的记录（用户 m19572）。
 *
 * 强停之后 Worker 直接没了，不会走到运行命令的收尾，所以 Host 也要调这里；
 * 但那时可能已经有新一趟在跑 —— 标识对不上就一个字节都不动。
 */
export function 清运行(项目目录: string, 本次运行?: string): void {
  if (!本次运行) return
  const 记录 = 读运行记录(项目目录)
  if (记录.本次运行 !== 本次运行) return
  const 下: 运行记录 = { 上次: 记录.上次, 测试报错: 记录.测试报错 }
  // 自己那一次的停止请求一并清掉，别让它去掐下一次重跑
  if (记录.要求结束 !== undefined && 记录.要求结束 !== 本次运行) 下.要求结束 = 记录.要求结束
  写运行记录(项目目录, 下)
}
