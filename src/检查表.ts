/** 这个命令要不要跑某个码，返回 0/1/2 */
export function 查级别(命令: 命令名, 码: 检查码): 处理 {
  return 检查表[命令]?.[码] ?? 0
}

/** 这个命令标 2 的码（要先跑、有错就拦） */
export function 拦截码(命令: 命令名): 检查码[] {
  return (Object.keys(检查表[命令] ?? {}) as 检查码[]).filter((k) => 检查表[命令][k] === 2)
}

/** 这个命令标 1 的码（命令生效后再改） */
export function 修改码(命令: 命令名): 检查码[] {
  return (Object.keys(检查表[命令] ?? {}) as 检查码[]).filter((k) => 检查表[命令][k] === 1)
}

