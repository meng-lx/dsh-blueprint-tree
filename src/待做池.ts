/**
 * 用户 2026-11-15（原话）：
 *   「待做池把 $结束→对应蓝图的蓝图单元下游做了, 蓝图单元→蓝图入口单元,
 *     这个必须状态机做, 不然背压会出问题」
 *
 * ⇒ 展开放在**待做池模块**里（状态机只管 `Start_` 筛选、软单元的假还差、强制），
 *   这样「录入什么」在进池前就定死了，背压不会被绕过去。
 *
 * 规则：
 *   `$结束`
 *     · 在**主蓝图**里 ⇒ 结束信号（不是真结束，只是通知）
 *     · 在**子蓝图**里 ⇒ 回到父图那个「子蓝图单元」的下游
 *   `子蓝图` 类型的单元 ⇒ 换成它子图的入口单元
 *   `循环向量` ⇒ 目标单元 + `⟳`（由调用方决定什么时候用这个标记）
 *   普通 ⇒ 原样
 */
export function 展开下游(
  从: 单元标识 & { 父单元?: 单元标识 },
  下层: string[],
  选项: {
    读蓝图: (名: string) => 蓝图 | undefined
    主蓝图名: string
    /**
     * 不进子图（用户 2026-11-15：蓝图测试「子蓝图单元输出或随机数」）。
     *
     * 为真时「子蓝图」单元当普通单元看 —— 它不进子图，而是由调用方
     * 给它一个假方法（返回手给或随机的输出）。这样蓝图测试不会跨蓝图。
     */
    不进子图?: boolean
  },
): { 下游: (单元标识 & { 循环?: boolean; 跳过?: 单元标识; 父单元?: 单元标识; 发出端?: 单元标识 })[]; 结束: boolean } {
  const 下游: (单元标识 & { 循环?: boolean })[] = []
  let 结束 = false

  // 如果**我自己**就是循环向量 ⇒ 我的下游全部都带 ⟳
  const 本图 = 选项.读蓝图(从.蓝图)
  const 我从循环来 = 本图?.单元.find((u) => u.名 === 从.单元)?.类型 === '循环向量'

  for (const 名 of 下层) {
    // ── $结束 ──
    if (名 === 结束标记) {
      if (从.蓝图 === 选项.主蓝图名) {
        结束 = true
        continue
      }
      // 子图走到出口 ⇒ 不再把父图的下游抄进「下游」里（2026-11-25 硬子图）：
      // 父图那个子蓝图格子自己是池里的一条，它的下游在它被取走时就录好了，
      // 出口这里只要「销掉父格子」（由状态机收尾的 到一次(父单元) 完成）。
      continue
    }

    const 图 = 选项.读蓝图(从.蓝图)
    const 单元 = 图?.单元.find((u) => u.名 === 名)
    if (!单元) continue

    // ── 子蓝图 ⇒ 当普通格子录入（用户 2026-11-25：蓝图单元按硬单元处理）──
    // 以前这里直接换成子图入口；现在父格先按硬单元等齐入边，
    // 状态机取到它时再「运行对应蓝图的入口单元」（见 状态机.跑一个）。
    if (单元.类型 === '子蓝图' && !选项.不进子图) {
      下游.push({
        蓝图: 从.蓝图,
        单元: 名,
        发出端: 从,
        ...(从.父单元 ? { 父单元: 从.父单元 } : {}),
      })
      continue
    }

    // ── 循环向量 ⇒ 目标 + 循环标记 ──
    if (单元.类型 === '循环向量') {
      for (const 目标 of 单元.下层 ?? []) {
        if (目标 === 结束标记) continue
        // 目标本身是子蓝图 ⇒ 回边拉起的是「父图那个子蓝图格子」（2026-11-25 硬子图），
        // 状态机取到它时会重新进入子图入口。
        const 目标单元 = 图?.单元.find((u) => u.名 === 目标)
        if (目标单元?.类型 === '子蓝图' && !选项.不进子图) {
          下游.push({
            蓝图: 从.蓝图,
            单元: 目标,
            循环: true,
            发出端: 从,
            ...(从.父单元 ? { 父单元: 从.父单元 } : {}),
          })
          continue
        }
        下游.push({
          蓝图: 从.蓝图,
          单元: 目标,
          循环: true,
          ...(从.父单元 ? { 父单元: 从.父单元 } : {}),
        })
      }
      continue
    }

    // ── 普通 ──
    // 子图里跑的所有单元都要带着「我从父图哪个子蓝图进来的」，
    // 否则它们走到 $结束 时回溯不到父图（用户 m04327）
    下游.push({
      蓝图: 从.蓝图,
      单元: 名,
      发出端: 从,
      ...(从.父单元 ? { 父单元: 从.父单元 } : {}),
    })
  }

  return { 下游, 结束 }
}
