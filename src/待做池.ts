/** 内部用的键 —— 只在 Map / 比较里用；对外一律走结构体比较 */
function 键(项: 单元标识 & { 时间戳: number; 符号: typeof 循环符号 | null; 启动?: string }): string {
  return [项.蓝图, 项.单元, String(项.时间戳), 项.符号 ?? '', 项.启动 ?? ''].join('\u0000')
}

/** 比较两个「单元标识」是不是同一个 */
export function 是同一单元(a: 单元标识, b: 单元标识): boolean {
  return a.蓝图 === b.蓝图 && a.单元 === b.单元
}

// ─── 展开下层（用户 2026-11-15 定：这三件归**待做池**，不归状态机） ───
//
//   「待做池把$结束→对应蓝图的蓝图单元下游做了,蓝图单元→蓝图入口单元,
//     这个必须状态机做,不然背压会出问题」
//
//   ⚠️ 他的意思是：这些**替换**必须发生在「录进池」的那一步，
//      如果状态机先替换完再录，就绕过了池的容量判断，背压失效。

/**
 * 「这张图是谁的子蓝图」—— 扫全项目的图名，找第一张里名叫 `图名` 的子蓝图单元。
 * 子蓝图单元名 = 蓝图名，全项目唯一，所以扫一遍就能定。
 */
export function 找谁的子蓝图(图名: string, 选项: 展开选项): 单元标识 | undefined {
  if (图名 === 选项.主蓝图名) return undefined
  for (const 候选 of 选项.蓝图名们?.() ?? []) {
    if (候选 === 图名) continue
    const 图 = 选项.读蓝图(候选)
    const 单元 = 图?.单元?.find((u) => u.名 === 图名)
    if (单元 && 单元.类型 === '子蓝图') return { 蓝图: 候选, 单元: 图名 }
  }
  return undefined
}

