const 结束标记 = '$结束'

// 待做池 —— 状态机的调度核心
//
// 用户 2026-11-15 定的形态（原话）：
//   「状态机给待做池一个信号，待做池返回一个单元并且给这个单元标一个标签，
//    完成后再删除；录入阶段时如果发现下游在待做池中已有，不录入，
//    返回给状态机，让状态机等待……这样有背压，有上下游都就绪的保证，
//    并且用的资源比较少」
//
// ⇒ 池里**同一单元同一来源最多一条记录**（= 容量 1 的 place）；
//   「还差」就是令牌 —— 上游激发一次，就从下游的「还差」里删掉自己；
//   删空了 ⇒ 可执行。
//
// ⚠️ 单元标识一律用 `{ 蓝图, 单元 }` 结构体，**不拼字符串**
//    （用户 m04171：单元名里可能有 #、/、-，拼了会被拆坏）。
// ⚠️ 「还差」是有序数组，不是 Map/Set（用户 m04171：用无序的还得额外加标签）。
//
// ─── 唯一键（用户 2026-11-15 定） ───
//
//   蓝图 \0 单元名 \0 时间戳 \0 是否 ⟳
//
//   | 情况                | 最多几条 |
//   |---------------------|----------|
//   | 非并发 · 正常        | 1        |
//   | 非并发 · ⟳           | 1        |
//   | 并发 · 时间戳 t · 正常 | 1        |
//   | 并发 · 时间戳 t · ⟳    | 1        |
//
//   ⇒ 非并发时一个单元最多两条；并发时每个时间戳各有两条
//     （⟳ 在不同时间戳上可以有多份 —— 用户 m04254 纠正）。
//   ⚠️ 并发现在**不实现**（用户 m04254：后续限制入口不并发或再优化）；
//      所以时间戳一律填 0，但键里保留这一位。

export interface 单元标识 {
  蓝图: string
  单元: string
}

/** 循环入口的标记符号（U+27F3）—— 只当键后缀，不拼进单元名 */
export const 循环符号 = '⟳' as const

export interface 待做项 extends 单元标识 {
  /** 还差哪些上游（有序数组） */
  还差: 单元标识[]
  /** 被谁占着 —— 取走时打上，完成时整条删掉 */
  标签: string | null
  /** 并发用的时间戳；非并发一律 0 */
  时间戳: number
  /** 是不是从循环向量进来的 */
  符号: typeof 循环符号 | null
  /**
   * 这一项是从哪个「子蓝图单元」进来的。
   * 子图里的单元走到 `$结束` 时，要回到父图这个单元的下游 —— 用户 2026-11-15。
   */
  父单元?: 单元标识
  /**
   * 是谁把这一项拉起来的（唤起者）。
   * 用户 m09563：软单元只处理「唤起它的那个单元」的输出，别的上游数据不传进来 ——
   * 共享数据没有清理机制，全传会把旧数据搅乱。
   */
  来自?: string
  /**
   * 测试标签（用户 m15078）：
   *   '单元' —— 只跑这一个单元，跑完直接当走到 $结束，不再展开下游；
   *   '蓝图' —— 跑这张图，但任何子图走到 `$结束` 就地结束，不回溯父图的下游。
   * 标签从池里的种子项一路继承给下游。
   */
  测试?: '单元' | '蓝图'
}

/** 内部用的键 —— 四元组，只在 Map 里用；对外一律走结构体比较 */
function 键(项: 单元标识 & { 时间戳: number; 符号: typeof 循环符号 | null }): string {
  return [项.蓝图, 项.单元, String(项.时间戳), 项.符号 ?? ''].join('\u0000')
}

/** 比较两个「单元标识」是不是同一个 */
export function 是同一单元(a: 单元标识, b: 单元标识): boolean {
  return a.蓝图 === b.蓝图 && a.单元 === b.单元
}

// ─── 展开下层（用户 2026-11-15 定：这三件归**待做池**，不归状态机） ───
//
//   「待做池把$结束→对应蓝图的蓝图单元下游做了,蓝图单元→蓝图入口单元,
//     这个必须状态机做,不然背压会出问题」
//
//   ⚠️ 他的意思是：这些**替换**必须发生在「录进池」的那一步，
//      如果状态机先替换完再录，就绕过了池的容量判断，背压失效。

/**
 * 「这张图是谁的子蓝图」—— 扫全项目的图名，找第一张里名叫 `图名` 的子蓝图单元。
 * 子蓝图单元名 = 蓝图名，全项目唯一，所以扫一遍就能定。
 */
export function 找谁的子蓝图(图名: string, 选项: 展开选项): 单元标识 | undefined {
  if (图名 === 选项.主蓝图名) return undefined
  for (const 候选 of 选项.蓝图名们?.() ?? []) {
    if (候选 === 图名) continue
    const 图 = 选项.读蓝图(候选)
    const 单元 = 图?.单元?.find((u) => u.名 === 图名)
    if (单元 && 单元.类型 === '子蓝图') return { 蓝图: 候选, 单元: 图名 }
  }
  return undefined
}

/** 读图 —— 交给调用方，池自己不碰磁盘 */
export interface 展开选项 {
  读蓝图: (名: string) => { 单元?: Array<{ 名: string; 类型: string; 下层?: string[] }>; 开始?: string | null } | undefined
  /**
   * 项目里所有蓝图的名字。
   * 子图套子图时，回溯一层之后还要知道「刚退出来的这张图，它是谁下面的子蓝图」，
   * 只能靠这个名字表去找（子蓝图单元名 = 蓝图名，全项目唯一）。
   */
  蓝图名们?: () => string[]
  /**
   * 测试模式（用户 m15078）：
   *   '单元' —— 下游一个都不录，这一格跑完就结束；
   *   '蓝图' —— 子图走到 `$结束` 就地结束，不回溯父图。
   */
  测试?: '单元' | '蓝图'
}

export interface 展开结果 {
  /** 真正要录进池的下游 */
  下游: 单元标识[]
  /** 走到 $结束 且没有父单元 ⇒ 这里就是终点 */
  结束了: boolean
  /** 下游里那些要从循环进来（⟳）的 */
  循环们: 单元标识[]
}

/**
 * 把一个单元的下层展开成「真正要录进池的标识」。
 *
 * 三种替换：
 *   `$结束`    → 有父单元（本项是子图里的）⇒ 父单元的下游；
 *               没有父单元（主蓝图）⇒ 结束信号
 *   子蓝图单元 → 子蓝图的入口单元（蓝图.开始）
 *   循环向量   → 它下游那个单元，但走 ⟳ 这条路
 */
export function 展开下层(
  自己: 待做项,
  本单元: { 名: string; 类型: string; 下层?: string[] },
  选项: 展开选项,
): 展开结果 {
  const 出: 展开结果 = { 下游: [], 结束了: false, 循环们: [] }

  // 单元测试：这一格跑完就是终点，下游一个都不录（用户 m15078
  // 「状态机遇到"单元测试"标签运行结束直接返回$结束」）
  if (选项.测试 === '单元') {
    出.结束了 = true
    return 出
  }

  const 本图 = 选项.读蓝图(自己.蓝图)

  for (const 下 of 本单元.下层 ?? []) {
    // ① $结束
    if (下 === 结束标记) {
      // 蓝图测试：哪张图走到出口都就地结束，不回溯父图（用户 m15078
      // 「如果一个有"蓝图测试"标签的下游是$结束,不用找蓝图单元的下游,直接返回$结束」）
      if (选项.测试 === '蓝图') {
        出.结束了 = true
        continue
      }
      if (自己.父单元) {
        // 子图到头 ⇒ 回到父图那个子蓝图单元的下游
        const 父图 = 选项.读蓝图(自己.父单元.蓝图)
        const 父 = 父图?.单元?.find((u) => u.名 === 自己.父单元!.单元)
        for (const 再下 of 父?.下层 ?? []) {
          if (再下 === 结束标记) continue
          出.下游.push({ 蓝图: 自己.父单元.蓝图, 单元: 再下 })
        }
      } else {
        出.结束了 = true
      }
      continue
    }

    const 下单元 = 本图?.单元?.find((u) => u.名 === 下)
    if (!下单元) continue

    // ② 子蓝图 ⇒ 换成它自己的入口
    if (下单元.类型 === '子蓝图') {
      const 子图 = 选项.读蓝图(下单元.名)
      const 入口 = 子图?.开始
      if (入口) 出.下游.push({ 蓝图: 下单元.名, 单元: 入口 })
      continue
    }

    // ③ 循环向量 ⇒ 下游走 ⟳
    if (下单元.类型 === '循环向量') {
      for (const 回 of 下单元.下层 ?? []) {
        if (回 === 结束标记) continue
        出.循环们.push({ 蓝图: 自己.蓝图, 单元: 回 })
      }
      continue
    }

    // ④ 普通
    出.下游.push({ 蓝图: 自己.蓝图, 单元: 下 })
  }

  return 出
}

export class 待做池 {
  private 项们: 待做项[] = []
  private 等待者 = new Map<string, Array<() => void>>()

  /** 池里有没有这条（按四元组匹配） */
  找(项: 单元标识 & { 时间戳: number; 符号: typeof 循环符号 | null }): 待做项 | undefined {
    const k = 键(项)
    return this.项们.find((x) => 键(x) === k)
  }

  /**
   * 录入。
   * 池里**没有** ⇒ 直接进池，返回 undefined（上游可以结束）。
   * 池里**已有** ⇒ 不进池，返回一个 Promise —— 上游挂在上面**不结束**（背压）。
   *               等池里那条被取走并完成后，Promise 解决，上游重试录入。
   */
  录入(项: 待做项): Promise<void> | undefined {
    if (this.找(项)) {
      return new Promise<void>((解决) => {
        const k = 键(项)
        const 队 = this.等待者.get(k) ?? []
        队.push(解决)
        this.等待者.set(k, 队)
      })
    }
    this.项们.push(项)
    return undefined
  }

  /**
   * 取一个**真能做**的（还差空了、没被占），取走就打标签。
   * 先扫带 ⟳ 的，没有再扫正常的 —— 用户 m04239：
   *   「待做池返回状态机运行请求时，同单元优先返回带这种符号的，剩下的交给状态机」
   */
  取(): 待做项 | undefined {
    const 能做 = (x: 待做项) => x.标签 === null && x.还差.length === 0
    const 项 = this.项们.find((x) => x.符号 !== null && 能做(x)) ?? this.项们.find(能做)
    if (!项) return undefined
    项.标签 = '在跑'
    return 项
  }

  /** 完成：整条删掉，再唤醒等它腾位置的上游 */
  完成(项: 待做项): void {
    this.项们 = this.项们.filter((x) => x !== 项)
    const k = 键(项)
    for (const 唤 of this.等待者.get(k) ?? []) 唤()
    this.等待者.delete(k)
  }

  /**
   * 清空：一刀切（用户 2026-11-15：「结束就是结束当前项目所有正在跑的,
   * 并清空待做池和共享参数」）。
   *
   * 挂起等着腾位置的上游也一起放掉 —— 池都没了，等着的也没意义。
   */
  清空(): void {
    this.项们 = []
    for (const 唤们 of this.等待者.values()) for (const 唤 of 唤们) 唤()
    this.等待者.clear()
  }

  /** 上游来了一次：从下游**正常项**的「还差」里删掉自己，返回真删掉了 */
  到一次(蓝图: string, 单元: string, 上游: 单元标识): boolean {
    const 项 = this.项们.find((x) => x.蓝图 === 蓝图 && x.单元 === 单元 && x.符号 === null)
    if (!项) return false
    const 前 = 项.还差.length
    项.还差 = 项.还差.filter((x) => !是同一单元(x, 上游))
    return 项.还差.length < 前
  }

  /** 池里有几条 */
  get 长度(): number {
    return this.项们.length
  }

  /** 现在有没有能立刻做的 */
  get 有可执行(): boolean {
    return this.项们.some((x) => x.标签 === null && x.还差.length === 0)
  }

  /** 把所有项摊平（只读，给界面/调试用） */
  全部(): ReadonlyArray<Readonly<待做项>> {
    return this.项们
  }
}

