/** 失败时对外给的那个 Error：非 Error 的值要包成能看的文本（2026-11-26） */
function 失败错误(选项: 引擎选项): Error {
  const e = 选项.错误
  if (e instanceof Error) {
    // 用户 m19432 的第四个缺口：`message` 是 getter 时可以再抛。
    // 这里先试读一次，读不了就换成一个纯文本的 Error —— 别让诊断反过来把失败结果顶掉。
    try {
      void e.message
      return e
    } catch {
      return new Error("未知错误（读取错误信息时又抛了）")
    }
  }
  if (e === undefined || e === null) return new Error('方法抛了非 Error 的值')
  return new Error(出错文本(e))
}
/** 把任意异常变成文本：`Object.create(null)` 这种没有原型的对象也要能转（2026-11-26） */
function 出错文本(值: unknown): string {
  if (值 instanceof Error) {
    try {
      return 值.message
    } catch {
      return "未知错误（读取错误信息时又抛了）"
    }
  }
  if (typeof 值 === "string") return 值
  try {
    return String(值)
  } catch {
    try {
      return JSON.stringify(值) ?? "未知错误"
    } catch {
      return "未知错误（无法转成文本）"
    }
  }
}
export async function 跑(图: 蓝图, 选项: 引擎选项): Promise<运行结果> {
  const 池 = new 待做池()
  const 在跑 = new Map<待做项, Promise<void>>()
  const 跑了: string[] = []
  const 跑了明细: 跑过[] = []

  // 起点：默认是开始单元（还差为空，一进池就能取）；
  // 测试单元时直接把它塞进池（用户 m15078「把单元直接塞待做池里」），不从图头起步。
  const 起点 = 图.开始 ?? 图.单元.find((u) => u.类型 === '开始')?.名
  // 记住顶层入口，输出门禁靠它放行点火包（入口可以不是「开始」类型，测评第 6 条）
  选项.入口蓝图 = 图.名
  选项.入口单元 = 起点
  const 种子: 单元标识 = 选项.起始
    ? { 蓝图: 选项.起始.蓝图 || 图.名, 单元: 选项.起始.单元 }
    : { 蓝图: 图.名, 单元: 起点 ?? '' }
  if (!种子.单元) {
    写日志(选项, { 类型: '卡死', 蓝图: 图.名, 结局: '卡死', 剩下: 0, 错误: '图里没有入口（蓝图.开始 和「开始」类型单元都没有）' })
    return { 结局: '卡死', 剩下: [], 跑了, 跑了明细, 结束信号: 选项.结束信号 }
  }

  池.录入({
    蓝图: 种子.蓝图,
    单元: 种子.单元,
    还差: [],
    标签: null,
    时间戳: 0,
    符号: null,
    ...(选项.测试 ? { 测试: 选项.测试 } : {}),
  })

  // 终止（Phase 3，2026-11-26）：第一次观察到失败或中止就锁住原因、清池、
  // 放掉被背压挂住的上游，然后**立刻收场 —— 不等不合作的方法**。
  // 在途的那些回调看到 `已停` 就只做清理：不再提交共享/广播/父格输出、
  // 不再派新下游、不再触发 `完成()` 的重试、也不再回调改单元状态。
  let 终止原因: '失败' | '中止' | undefined
  const 终止 = (原因: '失败' | '中止'): void => {
    if (终止原因) return
    终止原因 = 原因
    选项.已停 = true
    if (原因 === '失败') 选项.失败 = true
    // 待办 + 暂存投递一起清掉，并在清空里唤醒被背压的等待者（让上游能退场）
    池.清空()
    if (原因 === '中止') {
      for (const 图名 of Object.keys(选项.共享数据)) delete 选项.共享数据[图名]
    }
  }

  for (;;) {
    // ⓪ 该不该一刀切（用户 2026-11-15：「先停运行的单元，再清空池子和参数」）
    if (!终止原因 && 选项.该停?.()) {
      终止('中止')
      写日志(选项, { 类型: '中止', 蓝图: 图.名, 结局: '中止' })
    }
    // 已经终止：不等在跑的那些，直接收场（Phase 3，2026-11-26）
    if (终止原因 === '中止') {
      return { 结局: '中止', 跑了, 跑了明细, 结束信号: 选项.结束信号 }
    }
    if (终止原因 === '失败') {
      写日志(选项, { 类型: '失败', 蓝图: 图.名, 结局: '失败', 单元: 选项.错误单元 ?? '' })
      return {
        结局: '失败',
        // `throw undefined` 也是失败：错误对象缺失时补一个可读的
        错误: 失败错误(选项),
        错误单元: 选项.错误单元 ?? '',
        跑了,
        跑了明细,
        结束信号: 选项.结束信号,
      }
    }

    // ① 把现在能做的全取出来并发跑
    //    收到结束信号（主蓝图里有单元走到 $结束）之后不再取新的，
    //    但在跑的那几个要等它们收尾（用户 m04327：结束信号是状态机的活）
    //    另外：已经有人抛错了（整轮注定失败）就不再派新的，
    //    免得「失败」之后还跑出新的副作用（首轮测评 2026-11-24）
    // 结束信号不再拦派发：已经放进池子的就该跑完，
    // 收工由「池空 / 卡死」决定（用户 2026-11-25：能放进池子就算结束）
    if (!选项.已停) {
      // 先把「上一轮暂不接收」的投递重试一遍（测评第 5 条）：
      // 上一格刚跑完腾出位置，这一轮就该把它们建成新的待办。
      池.重试()
      for (;;) {
        // 并发上限：池里可执行的再多，也最多同时挂这么多个
        // （用户 2026-11-15「并行优先」；默认见 选项.最多并发 的注释）
        if (选项.最多并发 !== undefined && 在跑.size >= 选项.最多并发) break
        const 项 = 池.取()
        if (!项) break
        const p = 跑一个(项, 选项, 池, 跑了, 跑了明细, 图)
          .catch((e) => {
            // 已经终止（首个失败/中止已锁）：晚到的异常不改诊断、不改状态
            if (终止原因) return
            // 方法抛错 ⇒ 整轮失败（用户 2026-10-16：非强制报错也停全图，
            // 强制的区别在检测阶段，不在运行时）
            // 首个失败保留诊断，后到的不覆盖（Phase 3，2026-11-26）
            选项.错误 = e
            // 用户 2026-11-15：失败的单元要记进运行记录（状态不动）
            选项.错误单元 = 项.单元
            // 先锁终止、清池、释放背压，再做诊断格式化 ——
            // `Object.create(null)` 抛出来时，旧写法 `String(e)` 会二次抛错，
            // 终止清理根本没执行（用户 m19349 实测，2026-11-26）
            终止('失败')
            写日志(选项, {
              类型: '失败',
              蓝图: 项.蓝图,
              单元: 项.单元,
              错误: 出错文本(e),
            })
            报单元跑完(选项, 项.蓝图, 项.单元, false)
          })
          .finally(() => {
            在跑.delete(项)
          })
        在跑.set(项, p)
      }
    }

    if (在跑.size > 0) {
      // ② 等一个跑完，再回来取；顺手带个闹钟，方法挂住时也能醒来查 `该停`
      await 等一个(在跑.values(), 选项.停轮询毫秒 ?? 200)
      continue
    }

    // ③ 没在跑的也没能取的
    // 有单元的方法抛了错 ⇒ 整轮失败（不管强制不强制，运行时都一样停）
    // 判据用 `选项.失败`，不用 `错误 !== undefined`（`throw undefined` 也失败）
    if (选项.失败) {
      写日志(选项, { 类型: '失败', 蓝图: 图.名, 结局: '失败', 单元: 选项.错误单元 ?? '' })
      return {
        结局: '失败',
        错误: 失败错误(选项),
        错误单元: 选项.错误单元 ?? '',
        跑了,
        跑了明细,
        结束信号: 选项.结束信号,
      }
    }
    // 没有在跑的：池里还有可执行的接着派，跑空了才收工
    // （用户 2026-11-25：出口提交、把下游放进池子就算这一格结束，
    //   不需要主循环在这里判断「是否执行中」）
    if (池.有可执行) continue
    if (池.长度 === 0) {
      写日志(选项, { 类型: '完成', 蓝图: 图.名, 结局: '完成' })
      return { 结局: '完成', 跑了, 跑了明细, 结束信号: !!选项.结束信号 }
    }
    // 池里还有，但全都不可执行 ⇒ 卡死
    const 剩 = 池.全部()
    写日志(选项, { 类型: '卡死', 蓝图: 图.名, 结局: '卡死', 剩下: 剩.length })
    return { 结局: '卡死', 剩下: 剩, 跑了, 跑了明细, 结束信号: false }
  }
}

/** 跑一个单元，然后按三步收尾 */
async function 跑一个(
  项: 待做项,
  选项: 引擎选项,
  池: 待做池,
  跑了: string[],
  跑了明细: 跑过[],
  入口图: 蓝图,
): Promise<void> {
  // 这一轮已经终止（失败/中止）：晚到的这条只退场，不提交任何东西（Phase 3）
  if (选项.已停) return

  // 入口图直接用内存里这份 —— 用户可能没给 `读蓝图` 提供入口图，
  // 而入口图是 `跑()` 的参数，本来就该以它为准
  const 图 = 项.蓝图 === 入口图.名 ? 入口图 : 选项.读蓝图(项.蓝图)
  const 单元们 = 图?.单元 ?? []
  const 本单元 = 单元们.find((u) => u.名 === 项.单元)

  if (!本单元) {
    池.完成(项)
    return
  }

  // 不跑的单元：算它做完（下游照样放行）
  if (该跳过(选项, 本单元)) {
    写日志(选项, { 类型: '跳过', 蓝图: 项.蓝图, 单元: 本单元.名 })
    跑了.push(本单元.名)
    跑了明细.push({ 蓝图: 项.蓝图, 单元: 本单元.名 })
    await 收尾(项, 本单元, 图!, 选项, 池, 图?.单元 ?? [], [])
    if (选项.已停) return
    池.完成(项)
    return
  }

  const 起跑 = Date.now()

  // 收集输入（按上层顺序）—— 数据从 GONGXIANG 里拿
  // 用户 m09563：软单元只拿「唤起它的那个单元」的输出；
  // 共享数据没有清理机制，把别的上游的旧数据一起塞进来会串味。
  // 硬单元不同：它要等齐 n 个上游才执行，执行时本来就该看到全部上游。
  const 上层表 = 算上层(图!)
  // 循环向量拿「发出它的那个单元」的名义（用户 m18019）：传参段、启动名都按这个名字
  const 换名 = 循环换名(图!)
  const 原名 = 本单元.类型 === '软' && 项.来自 ? [项.来自] : (上层表[本单元.名] ?? [])
  const 该取的 = 原名.map((x) => 换名[x] ?? x)
  // 子图入口的「来自」是父图那个子蓝图格子的名字，数据也在父图里
  // （格子自己不跑，靠子图出口把输出镜像过来，见下面的「镜像给父图」）。
  // 按单元名在图谱里找数据：本图找不到就翻别的图（子图入口的「来自」
  // 常常是父图里的某个单元名，数据在父图那张表里）。
  // `Start_` 是「这一格往哪走」的信令，不是数据，别往下游传 ——
  // 传过去会被下游的 `筛下层` 误当成选择单元的分流表。
  const 取数据 = (上: string): Record<string, unknown> => {
    // 来源带图名时按图取（复核 2026-11-25 第 1 节）：退两层再进兄弟子图，
    // 来源是父图格子，只按名字扫会先撞上本图里的同名单元。
    let 原始 = 项.来自图 && 上 === 项.来自
      ? 选项.共享数据[项.来自图]?.[上]
      : 选项.共享数据[项.蓝图]?.[上]
    let 出处 = 项.来自图 && 上 === 项.来自 ? 项.来自图 : 项.蓝图
    if (原始 === undefined) {
      for (const [图名, 图数据] of Object.entries(选项.共享数据)) {
        if (图数据?.[上] !== undefined) { 原始 = 图数据[上]; 出处 = 图名; break }
      }
    }
    if (process.env.FLOW_DEBUG) console.log('  [取] ' + 上 + ' ← ' + 出处)
    if (!原始) return {}
    let 有信令 = false
    const 干净: Record<string, unknown> = {}
    for (const [键, 值] of Object.entries(原始)) {
      if (键.startsWith('Start_')) { 有信令 = true; continue }
      干净[键] = 值
    }
    return 有信令 ? 干净 : 原始
  }
  // 数据随待办走（用户 2026-11-25）：这条待办登记过的「这一路交付的那份」优先。
  // 测评 2026-11-25 第 2 条：**登记过就只认登记过的** —— 没被选中的边走的是
  // 「按名字去共享数据里捞」，那一捞会把后写覆盖过的旧值（或压根没被选中的分支）
  // 塞进输入里，等于替上游猜数据。只有整条待办没有任何携带（点火 / 子图入口
  // 这类没有「上一格交付」的入口）时才退回按名字读。
  const 携带表 = new Map((项.携带 ?? []).map((x) => [x.来源, x.数据]))
  const 有携带 = 携带表.size > 0
  const 输入: 上游输入[] = 该取的.map((上) => ({
    来源: 上,
    数据: 携带表.get(上) ?? (有携带 ? {} : 取数据(上)),
  }))
  /**
   * 广播区（首轮测评 2026-11-24 修复）：
   * 标签为「广播」的单元把输出写进 `共享数据.__广播[单元名]`，
   * 但方法只收得到 `输入`（`(输入: 上游输入[])`，没有第二个参数），
   * 于是「写出去的广播谁都读不到」。这里按只读快照塞进输入，
   * 来源固定为 `__广播`：`输入.find(i => i.来源 === '__广播')?.数据`。
   * 深拷贝 —— 读者改嵌套值不会污染广播区里的原件。
   */
  const 广播区 = (选项.共享数据 as Record<string, Record<string, unknown>>).__广播
  if (广播区 && Object.keys(广播区).length > 0) {
    输入.push({ 来源: '__广播', 数据: 深拷贝(广播区) })
  }
  // 硬子图（2026-11-25）：子图入口拿到的是父图格子等齐的批次 ——
  // 保留各来源、不拍平；广播仍然另列一项。
  if (项.批次) {
    const 广播项 = 输入.filter((i) => i.来源 === '__广播')
    输入.length = 0
    for (const b of 项.批次) 输入.push({ 来源: b.来源, 数据: 深拷贝(b.数据) })
    for (const b of 广播项) 输入.push(b)
  }
  if (process.env.FLOW_DEBUG) {
    console.log('[输入] ' + 项.蓝图 + '/' + 本单元.名 + ' 来自=' + String(项.来自) + ' 键=' + Object.keys(输入[0]?.数据 ?? {}).join(','))
  }

  // 调方法
  const 方法 = 选项.方法[本单元.名]
  // 开始单元 = 点火口。它不跑方法，只把点火数据（项目 / 命令 / 参数 / 宿主）
  // 当作自己的输出吐给下游 —— 这是整张图唯一的全局入口，之后一律顺拓扑往下传。
  // 入口不再要求「开始」类型（测评第 6 条）：只要顶层图以点火方式跑起来，
  // 锚点指的那一格就是点火口 —— 它可以是软/硬单元，同样不跑方法，
  // 把手里的点火包（以及子图批次）交出去。没有点火时仍然按类型认（直接跑图/测试）。
  const 点火 = 本单元.类型 === '开始' || (选项.点火 !== undefined && 项.蓝图 === 选项.入口蓝图 && 本单元.名 === 选项.入口单元)
  // 开始 / 结束 / 循环向量 / 子蓝图 本来就不需要方法，别去问 AI。
  // （子蓝图格子只负责把下游换成子图入口，自己不产出数据）
  const 该有方法 = 本单元.类型 === '硬' || 本单元.类型 === '软' || 本单元.类型 === '选择'
  // 子蓝图格子（2026-11-25 硬子图调度）：它自己没方法、输出 {}，
  // 按硬单元在父图排队；取到它时由状态机把子图入口放进池子。
  const 是子图格 = 本单元.类型 === '子蓝图' && !选项.不进子图
  let 输出: Record<string, unknown> = {}
  if (点火) {
    输出 = { ...((选项.点火 ?? {}) as Record<string, unknown>) }
    // 硬子图入口（2026-11-25）：父格等齐的批次要能传进来 ——
    // 入口本身是点火口（没有方法），批次按来源合并进输出，
    // 覆盖不了的键仍用点火包（宿主/配置/项目这些能力字段）。
    if (项.批次 && 项.批次.length > 0) {
      const 合并: Record<string, unknown> = { ...输出 }
      for (const b of 项.批次) {
        const 值 = b.数据 as Record<string, unknown>
        for (const [k, v] of Object.entries(值 ?? {})) 合并[k] = v
      }
      输出 = 合并
    }
  } else if (方法) {
    // await 一下：方法可以是 async 的（用户 2026-11-15「并行优先」）
    输出 = (await 方法(输入)) ?? {}
  } else if (该有方法 && 选项.ai处理) {
    // 没方法 ⇒ 这一格直接交给 AI 处理（用户 2026-11-16：有些单元没法用代码，
    // 存在的目的就是让 AI 处理）。
    // AI 可以只回一段文本（包成 { 文本 } 给下游），也可以回一整个输出对象
    // —— 选择单元要靠 Start_<下游名> 决定往哪走，不能再套一层。
    const 产出 = await 选项.ai处理(项.蓝图, 本单元.名, 输入)
    输出 = typeof 产出 === 'string' ? { 文本: 产出 } : ((产出 ?? {}) as Record<string, unknown>)
  }

  // 终止了（失败/中止）：方法已经跑起来了，结果一律不提交
  // （不写共享数据、不改状态、不录下游、也不再触发 `完成()` 的重试 —— Phase 3）
  if (选项.已停) return

  /**
   * 输出门禁（2026-11-25 开发交接第 1 节）：普通输出必须是平坦记录、字段值为原始值。
   * 内部通道 = 由 `点火` 启动的**链路自己那几张图**（格式化链路 / 自举链路要逐格传包，
   * 含宿主与嵌套参数）。被链路跑的那个项目里的单元照样过门禁 —— 否则「经链路跑」
   * 和「直接跑图」对同一张蓝图的检查口径不一致（测评 2026-11-25 第 3 条）。
   * 判定：点火包里带 `参数.蓝图内部 === true`（controller 点火链路时打的就是这个标），
   * 链路**替别人跑**的那一趟（`跑图` 里内层运行）会把标改成 false，所以被跑项目的
   * 单元照样过门禁（测评 2026-11-25 第 3 条）。
   * 没点火 / 没打标的运行（单元测试、直接跑图）一律走门禁。
   * 不合法直接抛错 ⇒ 上面 `.catch` 记这一格失败，不落盘、不激发下游。
   */
  const 点火参数 = (选项.点火 as { 参数?: Record<string, unknown> } | undefined)?.参数
  // 入口单元的输出**就是点火包**（入口不再要求「开始」类型，见测评第 6 条），
  // 它天然不是「普通数据」，一律放行。
  const 是顶层入口 = 项.蓝图 === (选项.入口蓝图 ?? '') && 本单元.名 === (选项.入口单元 ?? '')
  const 内部流 = (!!点火参数 && 点火参数.蓝图内部 === true) || (选项.点火 !== undefined && 本单元.类型 === '开始') || (选项.点火 !== undefined && 是顶层入口)
  if (process.env.FLOW_DEBUG) {
    console.log('[门禁]', 项.蓝图 + '/' + 本单元.名, '内部流=' + 内部流, '键=' + Object.keys(输出 ?? {}).join(','))
  }
  if (!内部流) {
    输出 = 校验输出(项.蓝图, 本单元.名, 输出)
  }

  // 写共享数据
  const 本图数据 = (选项.共享数据[项.蓝图] ??= {})
  本图数据[本单元.名] = 输出

  // 镜像给父图的事放到下面「筛过之后」—— 要看这一格是不是真的走到子图出口。

  // 用户 m09527：标签为「广播」的单元，输出另外写进全局广播区 ——
  // 任何单元都能读（`共享.__广播['单元名']`），不靠连线传。
  // 校验单元用它把「该改什么」的清单发给执行单元。
  if (本单元.标签 === '广播') {
    const 共享 = 选项.共享数据 as Record<string, Record<string, Record<string, unknown>>>
    const 广播区 = (共享.__广播 ??= {})
    // 深拷贝（复核 2026-11-25 第 2 节「普通输入可绕过广播只读隔离」）：
    // 以前这里和本图那份输出是同一个对象，别人顺着普通边改嵌套值，
    // 广播读者就会看到被改过的值。
    广播区[本单元.名] = 深拷贝(输出)
  }

  跑了.push(本单元.名)

  // 用户 2026-11-15：每个单元跑完就改状态，不是一起改
  报单元跑完(选项, 项.蓝图, 本单元.名, true)

  // 下游：状态机只做「按 Start_X 筛」，其余（$结束 / 子蓝图 / 循环向量）
  // 全部交给待做池的 `展开下游`（用户 m04327：这几件归待做池，不然背压会出问题）
  const 筛过 = 筛下层(本单元, 输出)

  // 子图出口 ⇒ 把这一次的出口输出提交给父图那张子蓝图格子（整体覆盖，不合并）。
  // 旧写法是「每个子图单元跑完都往父格子合并一次」，导致：
  //   ① 子图中间单元的字段漏给父图；② 循环重入时读到上一轮的旧字段。
  // 2026-11-25 硬子图：父格子仍由子图出口「销」掉，但连续退两层时
  // 每一层的格子都还没收到数据 —— 出口输出要沿「父格子链」逐层提交，
  // 哪一层还没到它自己的 $结束 就停（那种情况下这一层还会继续跑）。
  // 子蓝图格子自己不产出数据：它下层里的 `$结束` 只表示「这张子图到这儿结束」，
  // 真正的出口输出由子图里那个走到 `$结束` 的单元提交（见下）。
  const 镜像链: 单元标识[] =
    !是子图格 && 项.父单元 && 筛过.includes(结束标记) ? 格子链(项.父单元, 选项) : []
  for (const 格 of 镜像链) {
    const 图数据 = (选项.共享数据[格.蓝图] ??= {})
    // 深拷贝（复核 2026-11-25 第 2 节）：浅拷贝会和本图里那份输出共享嵌套对象，
    // 下游改一下嵌套值就串到别人眼里。
    图数据[格.单元] = 深拷贝(输出)
    if (process.env.FLOW_DEBUG) console.log('[提交] ' + 格.蓝图 + '/' + 格.单元 + ' 键=' + Object.keys(图数据[格.单元] as Record<string, unknown>).join(','))
  }
  // 数据随待办走（用户 2026-11-25）：正在等这一格的那条待办，直接把这份输出带上，
  // 以后它跑的时候不再按名字去共享数据里捞（那种捞法会捞到后一次覆盖的值）。
  // `Start_` 是「这一格往哪走」的信令，不是数据：带上会让下游的 `筛下层` 误当成
  // 选择单元的分流表（测评 2026-11-25 第 2 条：只交付选中边的数据）。
  池.带数据({ 蓝图: 项.蓝图, 单元: 本单元.名 }, 剥信令(输出))
  for (const 格 of 镜像链) {
    池.带数据(格, 剥信令(输出))
    // 子蓝图格子到出口才算真的完：等它的待办（含软单元）这一刻才放行
    池.格子到(格)
  }
  // 最外层那个格子下层里写了 `$结束` ⇒ 整张图走到出口了（测评 2026-11-25 第 1 条）
  const 最外 = 镜像链[镜像链.length - 1]
  if (最外) {
    const 格图 = 选项.读蓝图(最外.蓝图)
    const 格单元 = 格图?.单元?.find((u) => u.名 === 最外.单元)
    if (格单元?.下层?.includes(结束标记)) 选项.结束信号 = true
  }
  // 用户 m15078：单元测试 —— 只跑这一个单元，跑完直接当走到 `$结束`，下游一个都不录
  const 测试模式 = 项.测试 ?? 选项.测试
  let 下游: ReturnType<typeof 展开下游>['下游'] = []
  let 结束 = false
  if (测试模式 === '单元') {
    结束 = true
  } else {
    const 展开 = 展开下游(项, 筛过, {
      读蓝图: 选项.读蓝图,
      蓝图名们: 选项.蓝图名们,
      主蓝图名: 选项.主蓝图名,
      ...(选项.不进子图 ? { 不进子图: true } : {}),
      // 用户 m15078：测试标签一路继承（单元测试的下游本来就不录，这里给蓝图测试用）
      ...(测试模式 ? { 测试: 测试模式 } : {}),
    })
    下游 = 展开.下游
    结束 = 展开.结束
  }
  if (结束) 选项.结束信号 = true

  // 硬子图（2026-11-25 用户设计）：子蓝图格子被取走 ⇒ 把这张子图的入口放进池子。
  // 入口带「我从父图哪个子蓝图格子进来」的身份，出口处再销掉父格子。
  // 入口是开始单元：不跑方法，输出只有点火包（没点火就是 {}）。
  if (是子图格) {
    const 子图 = 选项.读蓝图(本单元.名)
    const 入口 = 子图?.开始 ?? 子图?.单元.find((u) => u.类型 === '开始')?.名
    if (入口) {
      池.录入({
        蓝图: 本单元.名,
        单元: 入口,
        还差: [],
        标签: null,
        时间戳: 0,
        符号: null,
        父单元: { 蓝图: 项.蓝图, 单元: 本单元.名 },
        // 父格等齐的输入批次原样交给入口（保留各来源，不拍平）
        批次: 输入.filter((i) => i.来源 !== '__广播'),
        ...(测试模式 ? { 测试: 测试模式 } : {}),
      })
    }
  }


  // 用户 m09563：给下游每项记上「是谁拉起来的」——
  // 软单元下次被取出时只拿这一项的输出（见上面的 该取的）。
  // 跨子图时「谁拉起来的」是**上一层那个子蓝图格子**：子图出口的 $结束
  // 往上跳时，父图里真正的上一格是 项.父单元.单元（例如 准备环境 → 命令层），
  // 不是子图里刚跑完的那个单元（报错格式）。
  for (const 下 of 下游) {
    if (下.来自) continue
    // 逻辑发出端（复核 2026-11-25 第 1 节：退两层后进兄弟子图时来源写成内层单元）。
    // 待做池展开时把「这条边是从哪一格发出来的」随边带下来；逐层回溯只会
    // 保留最近一层的 跳过，指不到真正的发出格子。
    if (下.发出端) {
      下.来自 = 下.发出端.单元
      下.来自图 = 下.发出端.蓝图
      continue
    }
    // 子图出口往上跳时，回溯出来的下游带「跳过」= 那一层被跳过的格子。
    // 它就在下游自己的图里，正好是「这条边在下一格眼里的上游」，优先用它。
    if (下.跳过 && 下.跳过.蓝图 === 下.蓝图) {
      下.来自 = 下.跳过.单元
      下.来自图 = 下.跳过.蓝图
      continue
    }
    // 跨图（下在别的图里）：「谁拉起来的」是**下所在那一层**的上游格子 ——
    //   · 父图里同级的另一个子图入口（命令层 → 蓝图命令）：来自 = 命令层
    const 父 = 项.父单元
    const 跨图 = !!父 && 下.蓝图 !== 项.蓝图 &&
      (下.蓝图 === 父.蓝图 || (!!下.父单元 && 下.父单元.蓝图 === 父.蓝图))
    下.来自 = 跨图 ? 父!.单元 : 本单元.名
    if (跨图) 下.来自图 = 父!.蓝图
  }

  写日志(选项, {
    类型: '跑完',
    蓝图: 项.蓝图,
    单元: 本单元.名,
    耗时: Date.now() - 起跑,
    输入,
    输出,
    下游: 筛过,
  })

  await 收尾(项, 本单元, 图!, 选项, 池, 下游, [], 镜像链, !是子图格, 输出)
  if (选项.已停) return
  池.完成(项)
}

/**
 * 三步收尾（用户 2026-11-15）：
 *   ① 先给下游录一条（还差 = 下游的全部上游）
 *   ② 再把自己从别人的「还差」里删掉
 *   ③ 卡死检测在主循环里做
 */
/** 循环向量 → 发出它的单元名（与 src/方法命令.ts 的 循环换名表 一致） */
function 循环换名(图: 蓝图): Record<string, string> {
  const 出: Record<string, string> = {}
  for (const u of 图.单元 ?? []) {
    if (u.类型 !== '循环') continue
    const 上游 = (图.单元 ?? []).find((x) => (x.下层 ?? []).includes(u.名))
    if (上游) 出[u.名] = 上游.名
  }
  return 出
}

async function 收尾(
  项: 待做项,
  本单元: 单元,
  图: 蓝图,
  选项: 引擎选项,
  池: 待做池,
  下游: (单元标识 & { 是结束?: boolean; 跳过?: 单元标识; 发出端?: 单元标识 })[],
  上游们: 单元标识[],
  镜像们: 单元标识[] = [],
  自完成 = true,
  输出: Record<string, unknown> = {},
): Promise<void> {
  // 这一轮已经终止（失败/中止）：收尾什么都不做
  // —— 在途回调不许再提交共享/广播/父格输出、不许再派下游（Phase 3）
  if (选项.已停) return
  const 我: 单元标识 = { 蓝图: 项.蓝图, 单元: 本单元.名 }
  // 交付名义：循环向量用它上游（发出它的单元）的名字，软单元靠这个名字选传参
  const 发起名 = 循环换名(图)[本单元.名] ?? 本单元.名
  // 测试标签（用户 m15078）：种子上带的标签，一路传给下游
  const 测试模式 = 项.测试 ?? 选项.测试

  // 测试时跳过「断联」单元：连不到开始 / 到不了结束的格子不跑（用户 m15078）。
  // 按图缓一次，免得每个下游都重算一遍可达集。
  const 活表 = new Map<string, Set<string>>()
  const 活着 = (蓝图名: string): Set<string> => {
    let 集 = 活表.get(蓝图名)
    if (!集) {
      const g = 选项.读蓝图(蓝图名)
      集 = g ? 活的单元(g) : new Set<string>()
      活表.set(蓝图名, 集)
    }
    return 集
  }

  // 「选择分支里的格子」——从任一选择单元顺下层能走到的单元（含选择自己）。
  // 子蓝图格子（硬子图）不该等这些：走哪条 只调一支，另一支永远不会跑，
  // 硬等它等于永远等（测评 2026-11-25 第 2 条：只交付选中边）。
  const 分支表 = new Map<string, Set<string>>()
  const 分支里 = (蓝图名: string): Set<string> => {
    let 集 = 分支表.get(蓝图名)
    if (!集) {
      集 = new Set<string>()
      const g = 选项.读蓝图(蓝图名)
      for (const 选 of g?.单元 ?? []) {
        if (选.类型 !== '选择') continue
        const 栈 = [...(选.下层 ?? [])]
        while (栈.length > 0) {
          const 名 = 栈.pop()!
          if (名 === 结束标记 || 集.has(名)) continue
          集.add(名)
          const u = g!.单元.find((z) => z.名 === 名)
          for (const 下 of u?.下层 ?? []) 栈.push(下)
        }
      }
      分支表.set(蓝图名, 集)
    }
    return 集
  }

  // ① 录下游（终止了 ⇒ 不再派新的；Phase 3 起判据只看「已停」）
  for (const 下 of 下游) {
    if (选项.已停) break
    if (下.是结束) continue // $结束：主蓝图里就是终点
    const 子图 = 下.蓝图 === 项.蓝图 ? 图 : 选项.读蓝图(下.蓝图)
    const 下单元 = 子图?.单元.find((u) => u.名 === 下.单元)
    if (!下单元) continue

    // 只录正常 / 提醒（用户 m04228 第①条）
    if (该跳过(选项, 下单元)) continue

    // 测试里断联的格子不跑（用户 m15078）
    if (测试模式 && !活着(下.蓝图).has(下.单元)) continue

    // 开始单元只启动一次（用户 2026-11-15：「开始单元强制只启动一次(开始有可能进循环)」）
    // 全项目测试传这个：循环向量回到开始时不重录，否则会无限启动。
    // 入口不再要求「开始」类型（测评第 6 条），所以锚点指的那一格也算入口。
    if (选项.开始只一次 && (下单元.类型 === '开始' || (下.蓝图 === 图.名 && 下.单元 === 图.开始))) continue

    // 循环向量回来的那条 ⇒ 还差是空的，立刻能跑（不进「等上游」）
    const 是循环 = 下.循环 === true

    // 软单元录入时不算上游 ⇒ 还差 []
    // 「选择」类型的上游不算：它调不调由运行时 Start_X 定，等它等于永远等
    const 本图 = 子图!
    const 还差 = 是循环
      ? []
      : 下单元.类型 === '软'
        ? []
        : (算上层(本图)[下单元.名] ?? []).filter((x) => {
            const t = 本图.单元.find((u) => u.名 === x)?.类型
            // 「选择」调不调由运行时 Start_X 定；「循环向量」是回边，
            // 第一次进这个单元时它还没跑过 —— 两者都不能算进「还差」
            // 「跳过」= 子图出口回溯到父图时，父图那个子蓝图单元自己从没跑过
            if (下.跳过 && 下.跳过.单元 === x) return false
            // 子蓝图格子（硬）：不等「只有选择分支才会跑到」的上游（测评第 2 条）
            if (下单元.类型 === '子蓝图' && 分支里(下.蓝图).has(x)) return false
            return t !== '选择' && t !== '循环向量'
          })

    // 并发单元：每条新待办各分一个递增时间戳（用户 m04254）
    const 时间戳 = 下单元.标签 === '并发' ? (选项.并发计数 = (选项.并发计数 ?? 0) + 1) : 0

    // 池里已有这条 ⇒ 不重复录。
    // ⚠️ 不能在这里 await 挂起：下游那条可能还在等别的上游，
    //    它没被取走就不会完成，await 会把自己也挂死（整条链死锁）。
    //    它的「还差」由下面第②步统一删。
    // 启动名进键（用户 2026-11-25）：软单元每次由哪一格拉起都要分开记，
    // 状态机才知道该把哪一格的数据传给它；硬单元不加 —— 两路到达合成同一条待办。
    const 目标单元 = 选项.读蓝图(下.蓝图)?.单元?.find((u) => u.名 === 下.单元)
    池.录入({
      蓝图: 下.蓝图,
      单元: 下.单元,
      还差: 还差.map((x) => ({ 蓝图: 下.蓝图, 单元: x })),
      标签: null,
      时间戳,
      符号: 是循环 ? 循环符号 : null,
      ...(目标单元?.类型 === '软' ? { 启动: 发起名 } : {}),
      // 子蓝图格子拉起来的待办：格子自己跑完不算完，等子图走到 $结束 再放行
      ...(自完成 ? {} : { 等格子: 本单元.名 }),
      // 软单元要靠这一项只拿「拉起我的那一格」的输出（见 该取的）
      ...(下.来自 ? { 来自: 下.来自 } : {}),
      ...(下.来自图 ? { 来自图: 下.来自图 } : {}),
      // 子蓝图入口要记住「我是从父图哪个子蓝图单元进来的」，
      // 它走到 $结束 时要靠这个回溯父图的下游（用户 m04327）
      ...(下.父单元 ? { 父单元: 下.父单元 } : {}),
      // 测试标签一路继承（用户 m15078）
      ...(测试模式 ? { 测试: 测试模式 } : {}),
      // 数据随待办走（用户 2026-11-25）：这一路交付的就是这一格的输出
      携带: [{ 来源: 发起名, 数据: 剥信令(深拷贝(输出)) }],
    })
  }

  // ② 删自己（遍历池里所有正常项）
  // 子图出口时，「自己」在父图眼里的身份是那张格子 —— 上游单元实体从来没跑过，
  // 只会以 父格子 的名字登记在别人的「还差」里，所以格子名也要一起销掉
  // （2026-11-25：只销 本单元 会让硬汇合永远等 子）。
  for (const x of 池.全部()) {
    if (x.符号 !== null) continue
    if (x.蓝图 === 项.蓝图 && x.单元 === 本单元.名) continue
    // 子蓝图格子不算做完：它的下游要等子图走到 $结束（出口处再销父格子）
    if (自完成) 池.到一次(x.蓝图, x.单元, 我)
    for (const 格 of 镜像们) 池.到一次(x.蓝图, x.单元, 格)
  }
}

/**
 * 状态机只做这一件：按 `Start_X` 筛下层。
 * `$结束` / 子蓝图 / 循环向量一律原样交给 `展开下游` 处理。
 *
 * 用户 2026-11-16：`$结束` 也要能选 —— 判断单元「撞了」就走 `$结束`，
 * 所以它跟普通下层一样看 `Start_$结束`，不能再无条件放行。
 */
function 筛下层(本单元: 单元, 输出: Record<string, unknown>): string[] {
  const 下层 = 本单元.下层 ?? []
  // 用户 m09527：统一分发 —— 校验单元各自判断「这条命令跟我有关吗」，
  // 无关就返回 { 参与: false }，什么都不发，下游一个都不启动。
  if (输出.参与 === false) return []
  const 有选择 = Object.keys(输出).some((k) => k.startsWith('Start_'))
  if (!有选择) return [...下层]
  return 下层.filter((下) => 输出[`Start_${下}`] === true)
}

/**
 * 去掉 `Start_` 信令，只留数据。
 * 随待办携带 / 送进子图入口的「包」里不能带上一格的分流表，
 * 否则下游 `筛下层` 会把它当成自己的选择表（测评 2026-11-25 第 2 条）。
 */
function 剥信令(数据: Record<string, unknown>): Record<string, unknown> {
  let 有信令 = false
  const 干净: Record<string, unknown> = {}
  for (const [键, 值] of Object.entries(数据 ?? {})) {
    if (键.startsWith('Start_')) { 有信令 = true; continue }
    干净[键] = 值
  }
  return 有信令 ? 干净 : (数据 ?? {})
}

/**
 * 子图出口要提交的「父格子链」（由内往外，逐层）。
 * 例：内图出口 ⇒ [外图/内, 主图/外]；只往上走「这一层自己也走到了 $结束」的那些层。
 * 2026-11-25：连续退两层时只提交一层会让最外层消费者拿不到数据。
 */
function 格子链(起点: 单元标识, 选项: 引擎选项): 单元标识[] {
  const 链: 单元标识[] = []
  const 走过 = new Set<string>()
  let 格: 单元标识 | undefined = 起点
  while (格) {
    const 键 = 格.蓝图 + '/' + 格.单元
    if (走过.has(键)) break
    走过.add(键)
    链.push(格)
    if (格.蓝图 === 选项.主蓝图名) break
    const 图 = 选项.读蓝图(格.蓝图)
    if (!图) break
    const 单元 = 图.单元.find((u) => u.名 === 格!.单元)
    if (!(单元?.下层 ?? []).includes(结束标记)) break
    const 上 = 找谁的子蓝图(格.蓝图, 选项)
    if (!上) break
    格 = 上
  }
  return 链
}

/** 等「在跑的那几个」里的一个；顺带每隔 `轮询毫秒` 醒一次，让主循环能重新查 `该停` */function 等一个(在跑: Iterable<Promise<unknown>>, 轮询毫秒: number): Promise<unknown> {
  const 闹钟 = new Promise((好) => {
    const t = setTimeout(好, Math.max(1, 轮询毫秒))
    ;(t as unknown as { unref?: () => void }).unref?.()
  })
  return Promise.race([...在跑, 闹钟])
}

/** 结构化深拷贝；运行时不支持 structuredClone 就退回 JSON */
/**
 * 深拷贝（保留函数）。
 *
 * 不能用 structuredClone / JSON：共享数据里带 `宿主`（一堆函数），
 * 两者都会把函数抹掉，格子里 `宿主.建目录?.(...)` 就成了 undefined。
 */
function 深拷贝<T>(值: T, 见过 = new WeakMap<object, unknown>()): T {
  if (值 === null || typeof 值 !== 'object') return 值
  const 原 = 值 as unknown as object
  const 已 = 见过.get(原)
  if (已 !== undefined) return 已 as T
  if (Array.isArray(值)) {
    const 出: unknown[] = []
    见过.set(原, 出)
    for (const x of 值) 出.push(深拷贝(x, 见过))
    return 出 as unknown as T
  }
  if (值 instanceof Date) return new Date(值.getTime()) as unknown as T
  if (值 instanceof Map) {
    const 出 = new Map()
    见过.set(原, 出)
    for (const [k, v] of 值) 出.set(k, 深拷贝(v, 见过))
    return 出 as unknown as T
  }
  if (值 instanceof Set) {
    const 出 = new Set()
    见过.set(原, 出)
    for (const v of 值) 出.add(深拷贝(v, 见过))
    return 出 as unknown as T
  }
  const 出: Record<string, unknown> = {}
  见过.set(原, 出)
  for (const k of Object.keys(值 as Record<string, unknown>)) 出[k] = 深拷贝((值 as Record<string, unknown>)[k], 见过)
  return 出 as unknown as T
}

/** 把上游名列表变成标识（蓝图后面补） */
function 上游列表(名们: string[]): 单元标识[] {
  return 名们.map((名) => ({ 蓝图: '', 单元: 名 }))
}
