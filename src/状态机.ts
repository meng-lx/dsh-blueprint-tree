/**
 * 单元方法：拿上游数组，返回一个对象（写进 GONGXIANG）。
 *
 * 用户 2026-11-15 定「并行优先」⇒ 返回 Promise 也行，状态机 await 它。
 * 只要方法内部有 await（fetch / fs.promises / 定时器），几百个单元就能
 * 同时挂着跑；纯同步的方法也不会出错，只是占着线程。
 */
// 用户 2026-11-16：方法只收「输入」这一个参数，不许读全局共享数据 ——
