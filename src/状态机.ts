// 用户 2026-11-15 定的三步（原话）：
//   「第一步,单元运行后下游生成这样的形式,
//    第二步,删除其他{}中上下游中此次激发待做池的单元名,
//    第三步检查是否有执行中单元,是则结束本次运行,
