/** 跑过一个单元的记录 —— 带蓝图名，因为一个项目里单元名会撞 */
export interface 跑过 {
  蓝图: string
  单元: string
}

/** 这些状态的单元被调起时，直接算它做完，不做任何操作（用户 2026-11-11 定） */
const 不跑的状态 = new Set(['报错', '废弃', '失效', '断联'])

/** 这个单元现在该不该跳过（用户 2026-11-15：测试方法无视状态） */
function 该跳过(选项: 引擎选项, u: 单元): boolean {
  // 断联（用户 m15078）：连不到开始或到不了结束的单元，测试里也不跑，
  // 跟运行一样当它不存在 —— 这是「测试不跑断联」的唯一通道。
  if (u.状态 === '断联') return true
  if (选项.无视状态) return false
  return 不跑的状态.has(u.状态)
}

/**
 * 跑一张蓝图。
 *
 * 从「开始」单元投第一个令牌，然后一直消费待做池，直到池空或者卡死。
 */
export async function 跑(图: 蓝图, 选项: 引擎选项): Promise<运行结果> {
  const 池 = new 待做池()
  const 在跑 = new Map<待做项, Promise<void>>()
  const 跑了: string[] = []
  const 跑了明细: 跑过[] = []

  // 起点：默认是开始单元（还差为空，一进池就能取）；
  // 测试单元时直接把它塞进池（用户 m15078「把单元直接塞待做池里」），不从图头起步。
  const 起点 = 图.开始 ?? 图.单元.find((u) => u.类型 === '开始')?.名
  const 种子: 单元标识 = 选项.起始
    ? { 蓝图: 选项.起始.蓝图 || 图.名, 单元: 选项.起始.单元 }
    : { 蓝图: 图.名, 单元: 起点 ?? '' }
  if (!种子.单元) {
    选项.日志?.({ 类型: '卡死', 蓝图: 图.名, 结局: '卡死', 剩下: 0, 错误: '图里没有「开始」单元' })
    return { 结局: '卡死', 剩下: [], 跑了, 跑了明细, 结束信号: 选项.结束信号 }
  }

  池.录入({
    蓝图: 种子.蓝图,
    单元: 种子.单元,
    还差: [],
    标签: null,
    时间戳: 0,
    符号: null,
    ...(选项.测试 ? { 测试: 选项.测试 } : {}),
  })

  for (;;) {
    // ⓪ 该不该一刀切（用户 2026-11-15：「先停运行的单元，再清空池子和参数」）
    if (选项.该停?.()) {
      // 先挂旗：在跑的那几个（可能正挂着等外部）晚到的结果一律作废
      选项.已停 = true
      池.清空()
      for (const 图名 of Object.keys(选项.共享数据)) delete 选项.共享数据[图名]
      选项.日志?.({ 类型: '中止', 蓝图: 图.名, 结局: '中止' })
      return { 结局: '中止', 跑了, 跑了明细, 结束信号: 选项.结束信号 }
    }

    // ① 把现在能做的全取出来并发跑
    //    收到结束信号（主蓝图里有单元走到 $结束）之后不再取新的，
    //    但在跑的那几个要等它们收尾（用户 m04327：结束信号是状态机的活）
    //    另外：已经有人抛错了（整轮注定失败）就不再派新的，
    //    免得「失败」之后还跑出新的副作用（首轮测评 2026-11-24）
    if (!选项.结束信号 && 选项.错误 === undefined) {
      for (;;) {
        // 并发上限：池里可执行的再多，也最多同时挂这么多个
        // （用户 2026-11-15「并行优先」；默认见 选项.最多并发 的注释）
        if (选项.最多并发 !== undefined && 在跑.size >= 选项.最多并发) break
        const 项 = 池.取()
        if (!项) break
        const p = 跑一个(项, 选项, 池, 跑了, 跑了明细, 图)
          .catch((e) => {
            // 方法抛错 ⇒ 整轮失败（用户 2026-10-16：非强制报错也停全图，
            // 强制的区别在检测阶段，不在运行时）
            选项.错误 = e
            // 用户 2026-11-15：失败的单元要记进运行记录（状态不动）
            选项.错误单元 = 项.单元
            选项.日志?.({
              类型: '失败',
              蓝图: 项.蓝图,
              单元: 项.单元,
              错误: e instanceof Error ? e.message : String(e),
            })
            选项.单元跑完?.(项.蓝图, 项.单元, false)
          })
          .finally(() => {
            在跑.delete(项)
          })
        在跑.set(项, p)
      }
    }

    if (在跑.size > 0) {
      // ② 等一个跑完，再回来取；顺手带个闹钟，方法挂住时也能醒来查 `该停`
      await 等一个(在跑.values(), 选项.停轮询毫秒 ?? 200)
      continue
    }

    // ③ 没在跑的也没能取的
    // 有单元的方法抛了错 ⇒ 整轮失败（不管强制不强制，运行时都一样停）
    if (选项.错误 !== undefined) {
      选项.日志?.({ 类型: '失败', 蓝图: 图.名, 结局: '失败', 单元: 选项.错误单元 ?? '' })
      return {
        结局: '失败',
        错误: 选项.错误,
        错误单元: 选项.错误单元 ?? '',
        跑了,
        跑了明细,
        结束信号: 选项.结束信号,
      }
    }
    // 结束信号到了：不再取新的，但在跑的要等它收尾
    if (选项.结束信号) {
      if (在跑.size > 0) {
        await Promise.race(在跑.values())
        continue
      }
      选项.日志?.({ 类型: '完成', 蓝图: 图.名, 结局: '完成' })
      return { 结局: '完成', 跑了, 跑了明细, 结束信号: true }
    }
    if (池.长度 === 0) {
      选项.日志?.({ 类型: '完成', 蓝图: 图.名, 结局: '完成' })
      return { 结局: '完成', 跑了, 跑了明细, 结束信号: false }
    }
    // 池里还有，但全都不可执行 ⇒ 卡死
    const 剩 = 池.全部()
    选项.日志?.({ 类型: '卡死', 蓝图: 图.名, 结局: '卡死', 剩下: 剩.length })
    return { 结局: '卡死', 剩下: 剩, 跑了, 跑了明细, 结束信号: false }
  }
}

/** 跑一个单元，然后按三步收尾 */
async function 跑一个(
  项: 待做项,
  选项: 引擎选项,
  池: 待做池,
  跑了: string[],
  跑了明细: 跑过[],
  入口图: 蓝图,
): Promise<void> {
  // 入口图直接用内存里这份 —— 用户可能没给 `读蓝图` 提供入口图，
  // 而入口图是 `跑()` 的参数，本来就该以它为准
  const 图 = 项.蓝图 === 入口图.名 ? 入口图 : 选项.读蓝图(项.蓝图)
  const 单元们 = 图?.单元 ?? []
  const 本单元 = 单元们.find((u) => u.名 === 项.单元)

  if (!本单元) {
    池.完成(项)
    return
  }

  // 不跑的单元：算它做完（下游照样放行）
  if (该跳过(选项, 本单元)) {
    选项.日志?.({ 类型: '跳过', 蓝图: 项.蓝图, 单元: 本单元.名 })
    跑了.push(本单元.名)
    跑了明细.push({ 蓝图: 项.蓝图, 单元: 本单元.名 })
    await 收尾(项, 本单元, 图!, 选项, 池, 图?.单元 ?? [], [])
    池.完成(项)
    return
  }

  const 起跑 = Date.now()

  // 收集输入（按上层顺序）—— 数据从 GONGXIANG 里拿
  // 用户 m09563：软单元只拿「唤起它的那个单元」的输出；
  // 共享数据没有清理机制，把别的上游的旧数据一起塞进来会串味。
  // 硬单元不同：它要等齐 n 个上游才执行，执行时本来就该看到全部上游。
  const 上层表 = 算上层(图!)
  const 该取的 = 本单元.类型 === '软' && 项.来自 ? [项.来自] : (上层表[本单元.名] ?? [])
  // 子图入口的「来自」是父图那个子蓝图格子的名字，数据也在父图里
  // （格子自己不跑，靠子图出口把输出镜像过来，见下面的「镜像给父图」）。
  // 按单元名在图谱里找数据：本图找不到就翻别的图（子图入口的「来自」
  // 常常是父图里的某个单元名，数据在父图那张表里）。
  // `Start_` 是「这一格往哪走」的信令，不是数据，别往下游传 ——
  // 传过去会被下游的 `筛下层` 误当成选择单元的分流表。
  const 取数据 = (上: string): Record<string, unknown> => {
    let 原始 = 选项.共享数据[项.蓝图]?.[上]
    let 出处 = 项.蓝图
    if (原始 === undefined) {
      for (const [图名, 图数据] of Object.entries(选项.共享数据)) {
        if (图数据?.[上] !== undefined) { 原始 = 图数据[上]; 出处 = 图名; break }
      }
    }
    if (process.env.FLOW_DEBUG) console.log('  [取] ' + 上 + ' ← ' + 出处)
    if (!原始) return {}
    let 有信令 = false
    const 干净: Record<string, unknown> = {}
    for (const [键, 值] of Object.entries(原始)) {
      if (键.startsWith('Start_')) { 有信令 = true; continue }
      干净[键] = 值
    }
    return 有信令 ? 干净 : 原始
  }
  const 输入: 上游输入[] = 该取的.map((上) => ({
    来源: 上,
    数据: 取数据(上),
  }))
  /**
   * 广播区（首轮测评 2026-11-24 修复）：
   * 标签为「广播」的单元把输出写进 `共享数据.__广播[单元名]`，
   * 但方法只收得到 `输入`（`(输入: 上游输入[])`，没有第二个参数），
   * 于是「写出去的广播谁都读不到」。这里按只读快照塞进输入，
   * 来源固定为 `__广播`：`输入.find(i => i.来源 === '__广播')?.数据`。
   * 深拷贝 —— 读者改嵌套值不会污染广播区里的原件。
   */
  const 广播区 = (选项.共享数据 as Record<string, Record<string, unknown>>).__广播
  if (广播区 && Object.keys(广播区).length > 0) {
    输入.push({ 来源: '__广播', 数据: 深拷贝(广播区) })
  }
  if (process.env.FLOW_DEBUG) {
    console.log('[输入] ' + 项.蓝图 + '/' + 本单元.名 + ' 来自=' + String(项.来自) + ' 键=' + Object.keys(输入[0]?.数据 ?? {}).join(','))
  }

  // 调方法
  const 方法 = 选项.方法[本单元.名]
  // 开始单元 = 点火口。它不跑方法，只把点火数据（项目 / 命令 / 参数 / 宿主）
  // 当作自己的输出吐给下游 —— 这是整张图唯一的全局入口，之后一律顺拓扑往下传。
  const 点火 = 本单元.类型 === '开始'
  // 开始 / 结束 / 循环向量 / 子蓝图 本来就不需要方法，别去问 AI。
  // （子蓝图格子只负责把下游换成子图入口，自己不产出数据）
  const 该有方法 = 本单元.类型 === '硬' || 本单元.类型 === '软' || 本单元.类型 === '选择'
  let 输出: Record<string, unknown> = {}
  if (点火) {
    输出 = (选项.点火 ?? {}) as Record<string, unknown>
  } else if (方法) {
    // await 一下：方法可以是 async 的（用户 2026-11-15「并行优先」）
    输出 = (await 方法(输入)) ?? {}
  } else if (该有方法 && 选项.ai处理) {
    // 没方法 ⇒ 这一格直接交给 AI 处理（用户 2026-11-16：有些单元没法用代码，
    // 存在的目的就是让 AI 处理）。
    // AI 可以只回一段文本（包成 { 文本 } 给下游），也可以回一整个输出对象
    // —— 选择单元要靠 Start_<下游名> 决定往哪走，不能再套一层。
    const 产出 = await 选项.ai处理(项.蓝图, 本单元.名, 输入)
    输出 = typeof 产出 === 'string' ? { 文本: 产出 } : ((产出 ?? {}) as Record<string, unknown>)
  }

  // 中止了：方法已经跑起来了，结果一律不提交（不写共享数据、不改状态、不录下游）
  if (选项.已停) {
    池.完成(项)
    return
  }

  // 写共享数据
  const 本图数据 = (选项.共享数据[项.蓝图] ??= {})
  本图数据[本单元.名] = 输出

  // 镜像给父图：子蓝图格子自己不产出数据，父图里「来自 = 格子名」的下游
  // 只能从格子名下拿 —— 子图最后一个跑完的单元把输出写进去。
  if (项.父单元) {
    const 父图数据 = (选项.共享数据[项.父单元.蓝图] ??= {})
    const 已有 = (父图数据[项.父单元.单元] ?? {}) as Record<string, unknown>
    父图数据[项.父单元.单元] = { ...已有, ...输出 }
  }

  // 用户 m09527：标签为「广播」的单元，输出另外写进全局广播区 ——
  // 任何单元都能读（`共享.__广播['单元名']`），不靠连线传。
  // 校验单元用它把「该改什么」的清单发给执行单元。
  if (本单元.标签 === '广播') {
    const 共享 = 选项.共享数据 as Record<string, Record<string, Record<string, unknown>>>
    const 广播区 = (共享.__广播 ??= {})
    广播区[本单元.名] = 输出
  }

  跑了.push(本单元.名)

  // 用户 2026-11-15：每个单元跑完就改状态，不是一起改
  选项.单元跑完?.(项.蓝图, 本单元.名, true)

  // 下游：状态机只做「按 Start_X 筛」，其余（$结束 / 子蓝图 / 循环向量）
  // 全部交给待做池的 `展开下游`（用户 m04327：这几件归待做池，不然背压会出问题）
  const 筛过 = 筛下层(本单元, 输出)
  // 用户 m15078：单元测试 —— 只跑这一个单元，跑完直接当走到 `$结束`，下游一个都不录
  const 测试模式 = 项.测试 ?? 选项.测试
  let 下游: ReturnType<typeof 展开下游>['下游'] = []
  let 结束 = false
  if (测试模式 === '单元') {
    结束 = true
  } else {
    const 展开 = 展开下游(项, 筛过, {
      读蓝图: 选项.读蓝图,
      蓝图名们: 选项.蓝图名们,
      主蓝图名: 选项.主蓝图名,
      ...(选项.不进子图 ? { 不进子图: true } : {}),
      // 用户 m15078：测试标签一路继承（单元测试的下游本来就不录，这里给蓝图测试用）
      ...(测试模式 ? { 测试: 测试模式 } : {}),
    })
    下游 = 展开.下游
    结束 = 展开.结束
  }
  if (结束) 选项.结束信号 = true

  // 用户 m09563：给下游每项记上「是谁拉起来的」——
  // 软单元下次被取出时只拿这一项的输出（见上面的 该取的）。
  // 跨子图时「谁拉起来的」是**上一层那个子蓝图格子**：子图出口的 $结束
  // 往上跳时，父图里真正的上一格是 项.父单元.单元（例如 准备环境 → 命令层），
  // 不是子图里刚跑完的那个单元（报错格式）。
  for (const 下 of 下游) {
    if (下.来自) continue
    // 往上跳：下是「同一父图里另一个格子」的入口 ⇒ 上一格是父图里刚跑完的那个格子
    const 往上 = 下.父单元 && 项.父单元 &&
      下.父单元.蓝图 === 项.父单元.蓝图 && 下.父单元.单元 !== 项.父单元.单元
    下.来自 = 往上 ? 项.父单元!.单元 : 本单元.名
  }

  选项.日志?.({
    类型: '跑完',
    蓝图: 项.蓝图,
    单元: 本单元.名,
    耗时: Date.now() - 起跑,
    输入,
    输出,
    下游: 筛过,
  })

  await 收尾(项, 本单元, 图!, 选项, 池, 下游)
  池.完成(项)
}

/**
 * 三步收尾（用户 2026-11-15）：
 *   ① 先给下游录一条（还差 = 下游的全部上游）
 *   ② 再把自己从别人的「还差」里删掉
 *   ③ 卡死检测在主循环里做
 */
async function 收尾(
  项: 待做项,
  本单元: 单元,
  图: 蓝图,
  选项: 引擎选项,
  池: 待做池,
  下游: (单元标识 & { 是结束?: boolean })[],
  上游们: 单元标识[],
): Promise<void> {
  const 我: 单元标识 = { 蓝图: 项.蓝图, 单元: 本单元.名 }
  // 测试标签（用户 m15078）：种子上带的标签，一路传给下游
  const 测试模式 = 项.测试 ?? 选项.测试

  // 测试时跳过「断联」单元：连不到开始 / 到不了结束的格子不跑（用户 m15078）。
  // 按图缓一次，免得每个下游都重算一遍可达集。
  const 活表 = new Map<string, Set<string>>()
  const 活着 = (蓝图名: string): Set<string> => {
    let 集 = 活表.get(蓝图名)
    if (!集) {
      const g = 选项.读蓝图(蓝图名)
      集 = g ? 活的单元(g) : new Set<string>()
      活表.set(蓝图名, 集)
    }
    return 集
  }

  // ① 录下游（中止了 / 已经失败 ⇒ 不再派新的；首轮测评 2026-11-24）
  for (const 下 of 下游) {
    if (选项.已停 || 选项.错误 !== undefined) break
    if (下.是结束) continue // $结束：主蓝图里就是终点
    const 子图 = 下.蓝图 === 项.蓝图 ? 图 : 选项.读蓝图(下.蓝图)
    const 下单元 = 子图?.单元.find((u) => u.名 === 下.单元)
    if (!下单元) continue

    // 只录正常 / 提醒（用户 m04228 第①条）
    if (该跳过(选项, 下单元)) continue

    // 测试里断联的格子不跑（用户 m15078）
    if (测试模式 && !活着(下.蓝图).has(下.单元)) continue

    // 开始单元只启动一次（用户 2026-11-15：「开始单元强制只启动一次(开始有可能进循环)」）
    // 全项目测试传这个：循环向量回到开始时不重录，否则会无限启动。
    if (选项.开始只一次 && 下单元.类型 === '开始') continue

    // 循环向量回来的那条 ⇒ 还差是空的，立刻能跑（不进「等上游」）
    const 是循环 = 下.循环 === true

    // 软单元录入时不算上游 ⇒ 还差 []
    // 「选择」类型的上游不算：它调不调由运行时 Start_X 定，等它等于永远等
    const 本图 = 子图!
    const 还差 = 是循环
      ? []
      : 下单元.类型 === '软'
        ? []
        : (算上层(本图)[下单元.名] ?? []).filter((x) => {
            const t = 本图.单元.find((u) => u.名 === x)?.类型
            // 「选择」调不调由运行时 Start_X 定；「循环向量」是回边，
            // 第一次进这个单元时它还没跑过 —— 两者都不能算进「还差」
            // 「跳过」= 子图出口回溯到父图时，父图那个子蓝图单元自己从没跑过
            if (下.跳过 && 下.跳过.单元 === x) return false
            return t !== '选择' && t !== '循环向量'
          })

    // 并发单元：每条新待办各分一个递增时间戳（用户 m04254）
    const 时间戳 = 下单元.标签 === '并发' ? (选项.并发计数 = (选项.并发计数 ?? 0) + 1) : 0

    // 池里已有这条 ⇒ 不重复录。
    // ⚠️ 不能在这里 await 挂起：下游那条可能还在等别的上游，
    //    它没被取走就不会完成，await 会把自己也挂死（整条链死锁）。
    //    它的「还差」由下面第②步统一删。
    池.录入({
      蓝图: 下.蓝图,
      单元: 下.单元,
      还差: 还差.map((x) => ({ 蓝图: 下.蓝图, 单元: x })),
      标签: null,
      时间戳,
      符号: 是循环 ? 循环符号 : null,
      // 软单元要靠这一项只拿「拉起我的那一格」的输出（见 该取的）
      ...(下.来自 ? { 来自: 下.来自 } : {}),
      // 子蓝图入口要记住「我是从父图哪个子蓝图单元进来的」，
      // 它走到 $结束 时要靠这个回溯父图的下游（用户 m04327）
      ...(下.父单元 ? { 父单元: 下.父单元 } : {}),
      // 测试标签一路继承（用户 m15078）
      ...(测试模式 ? { 测试: 测试模式 } : {}),
    })
  }

  // ② 删自己（遍历池里所有正常项）
  for (const x of 池.全部()) {
    if (x.符号 !== null) continue
    if (x.蓝图 === 项.蓝图 && x.单元 === 本单元.名) continue
    池.到一次(x.蓝图, x.单元, 我)
  }
}

/**
 * 状态机只做这一件：按 `Start_X` 筛下层。
 * `$结束` / 子蓝图 / 循环向量一律原样交给 `展开下游` 处理。
 *
 * 用户 2026-11-16：`$结束` 也要能选 —— 判断单元「撞了」就走 `$结束`，
 * 所以它跟普通下层一样看 `Start_$结束`，不能再无条件放行。
 */
function 筛下层(本单元: 单元, 输出: Record<string, unknown>): string[] {
  const 下层 = 本单元.下层 ?? []
  // 用户 m09527：统一分发 —— 校验单元各自判断「这条命令跟我有关吗」，
  // 无关就返回 { 参与: false }，什么都不发，下游一个都不启动。
  if (输出.参与 === false) return []
  const 有选择 = Object.keys(输出).some((k) => k.startsWith('Start_'))
  if (!有选择) return [...下层]
  return 下层.filter((下) => 输出[`Start_${下}`] === true)
}

/** 等「在跑的那几个」里的一个；顺带每隔 `轮询毫秒` 醒一次，让主循环能重新查 `该停` */
function 等一个(在跑: Iterable<Promise<unknown>>, 轮询毫秒: number): Promise<unknown> {
  const 闹钟 = new Promise((好) => {
    const t = setTimeout(好, Math.max(1, 轮询毫秒))
    ;(t as unknown as { unref?: () => void }).unref?.()
  })
  return Promise.race([...在跑, 闹钟])
}

/** 结构化深拷贝；运行时不支持 structuredClone 就退回 JSON */
function 深拷贝<T>(值: T): T {
  try {
    return structuredClone(值)
  } catch {
    try {
      return JSON.parse(JSON.stringify(值)) as T
    } catch {
      return 值
    }
  }
}

/** 把上游名列表变成标识（蓝图后面补） */
function 上游列表(名们: string[]): 单元标识[] {
  return 名们.map((名) => ({ 蓝图: '', 单元: 名 }))
}

