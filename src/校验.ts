export function 查单元(蓝图: 蓝图): 问题[] {
  const 出: 问题[] = []
  const 单元们 = 蓝图.单元 ?? []

  // A1 名字不能为空
  for (const [i, u] of 单元们.entries()) {
    if (typeof u.名 !== 'string' || !u.名.trim()) {
      出.push({ 码: 'A1', 级别: '错', 消息: `第 ${i + 1} 个单元没有名字`, 位置: `#${i + 1}` })
    }
  }

  // A2 名字本图内唯一
  const 次数 = new Map<string, number>()
  for (const u of 单元们) 次数.set(u.名, (次数.get(u.名) ?? 0) + 1)
  for (const [名, n] of 次数) {
    if (n > 1) 出.push({ 码: 'A2', 级别: '错', 消息: `单元「${名}」出现了 ${n} 次`, 位置: 名 })
  }

  for (const u of 单元们) {
    // A3 类型
    if (!(类型全部 as readonly string[]).includes(u.类型)) {
      出.push({
        码: 'A3',
        级别: '错',
        消息: `单元「${u.名}」的类型「${String(u.类型)}」不认（只能是 ${类型全部.join('/')}）`,
        位置: u.名,
      })
    }
    // A4 标签
    if (u.标签 !== undefined && !(标签全部 as readonly string[]).includes(u.标签)) {
      出.push({
        码: 'A4',
        级别: '错',
        消息: `单元「${u.名}」的标签「${String(u.标签)}」不认（只能是 ${标签全部.join('/')}）`,
        位置: u.名,
      })
    }
    // A5 状态
    if (u.状态 !== undefined && !(状态全部 as readonly string[]).includes(u.状态)) {
      出.push({
        码: 'A5',
        级别: '错',
        消息: `单元「${u.名}」的状态「${String(u.状态)}」不认（只能是 ${状态全部.join('/')}）`,
        位置: u.名,
      })
    }
    // A6 下层必须是字符串数组
    if (u.下层 !== undefined && (!Array.isArray(u.下层) || u.下层.some((x) => typeof x !== 'string'))) {
      出.push({ 码: 'A6', 级别: '错', 消息: `单元「${u.名}」的下层必须是字符串数组`, 位置: `${u.名}.下层` })
    }
  }

  return 出
}

