/**
 * @param 当前源码 方法.ts 的全文
 * @param 历史源码 方法历史.ts 的全文（可以不传）
 */
export function 查方法(蓝图: 蓝图, 当前源码: string, 历史源码?: string): 问题[] {
  const 出: 问题[] = []
  const 上层表 = 算上层(蓝图)

  // G1 方法文件语法必须正确
  const 语法 = 语法错(当前源码)
  if (语法.length) {
    for (const s of 语法) 出.push({ 码: 'G1', 级别: '错', 消息: `方法文件语法错：${s}` })
  }
  if (历史源码 !== undefined) {
    for (const s of 语法错(历史源码)) {
      出.push({ 码: 'G1', 级别: '错', 消息: `方法历史文件语法错：${s}` })
    }
  }

  // G2 方法里的 上游_X 集合 = 现算的上层集合（缺方法不报错）
  const 方法表 = 列出方法键(当前源码)
  for (const u of 蓝图.单元 ?? []) {
    const 文本 = 方法表.get(u.名)
    if (文本 === undefined) continue // 没方法不算错（用户 m02481：可以没有对应方法）
    const 写的 = [...文本.matchAll(/上游_([A-Za-z0-9_\u4e00-\u9fa5]+)/g)].map((m) => m[1])
    const 该有 = 上层表[u.名] ?? []
    const 写集 = new Set(写的)
    const 该集 = new Set(该有)
    const 多 = [...写集].filter((x) => !该集.has(x))
    const 少 = [...该集].filter((x) => !写集.has(x))
    if (多.length) {
      出.push({
        码: 'G2',
        级别: '警',
        消息: `方法「${u.名}」里取了不存在的上游：${多.join('、')}`,
        位置: u.名,
      })
    }
    if (少.length) {
      出.push({
        码: 'G2',
        级别: '警',
        消息: `方法「${u.名}」缺了上游：${少.join('、')}`,
        位置: u.名,
      })
    }
  }

  // G3 return 必须在最后一行
  for (const [键, 文本] of 方法表) {
    const 行 = 文本.split(/\r?\n/).map((s) => s.trim()).filter((s) => s.length > 0)
    // 块文本末尾自带方法的收尾 `}` / `};`，它们不是语句，先剔掉再看最后一行
    while (行.length && /^[})]+;?$/.test(行[行.length - 1]!)) 行.pop()
    const 最后 = 行[行.length - 1] ?? ''
    if (!最后.startsWith('return')) {
      出.push({
        码: 'G3',
        级别: '警',
        消息: `方法「${键}」最后一行不是 return`,
        位置: 键,
      })
    }
  }

  // G4 返回里的变量必须带显式类型标注
  // 用户 2026-11-15：「方法检测强制要求 const 名字: string = ... 这种写法」
  // ⇒ 随机数据的类型只能从这里拿（状态机要按类型造随机值）
  for (const [键, 文本] of 方法表) {
    const 返回 = 文本.match(/return\s*\{([\s\S]*?)\}\s*;?\s*$/)
    if (!返回) continue
    for (const 段 of 返回[1].split(',')) {
      const m = 段.match(/^\s*[A-Za-z_$\u4e00-\u9fa5][\w$\u4e00-\u9fa5]*\s*:\s*([A-Za-z_$\u4e00-\u9fa5][\w$\u4e00-\u9fa5]*)\s*$/)
      if (!m) continue
      const 变量 = m[1]
      const 声明 = 文本.match(
        new RegExp(`(?:const|let|var)\\s+${变量.replace(/[$]/g, '\\$')}\\s*([:=])`),
      )
      if (!声明 || 声明[1] === ':') continue
      出.push({
        码: 'G4',
        级别: '警',
        消息: `方法「${键}」的变量「${变量}」没写类型标注（要写成 const ${变量}: 类型 = ...）`,
        位置: 键,
      })
    }
  }

  return 出
}

/** 从源码里取出「键 → 属性全文」，解析不了就返回空表 */
function 列出方法键(源码: string): Map<string, string> {
  const 出 = new Map<string, string>()
  try {
    for (const 键 of 列出方法(源码, '方法')) {
      const 块 = 切方法(源码, 键, '方法')
      if (块) 出.set(键, 块.文本)
    }
  } catch {
    // 方法文件坏了 —— G1 会报，这里就当没有
  }
  return 出
}

/** 语法检查 */
function 语法错(源码: string): string[] {
  try {
    return 语法错误(解析(源码, '方法.ts'))
  } catch {
    return []
  }
}

