// D · 多上游硬单元
// ═══════════════════════════════════════════════════════════

/**
 * 用户 2026-11-10 的用途 2（原话）：
 *   「创建单元或修改单元的下层是否为多上游硬单元，否则无事发生，是则继续下一步，
 *     判断此硬单元最近支配单元（忽略循环），判断此支配单元属性，是选择单元则报 D3，
 *     不管是否都进行下一步，调用检测方法判断支配单元和此硬单元，
 *     路径上没有选择单元和多上游软单元则不报错否则报 D1，
 *     路径上蓝图一致性检查不通过报 D2」
 *
 * 「不连接开始的不用管，这些单元不会执行」（同一天）
 */
export function 查硬单元(蓝图: 蓝图, 读子图?: (名: string) => 蓝图 | undefined): 问题[] {
  const 出: 问题[] = []
  const 入口 = 蓝图.开始
  if (!入口) return 出

  const 活的 = 活的单元(蓝图)
  if (!活的.size) return 出

  const 有 = new Map((蓝图.单元 ?? []).map((u) => [u.名, u]))

  for (const u of 蓝图.单元 ?? []) {
    // 只看多上游硬单元（单上游的硬单元等价于普通顺序执行）
    if (u.类型 !== '硬') continue
    if (!活的.has(u.名)) continue
    if (上层们(蓝图, u.名).length < 2) continue

    const 支配者 = 最近支配者(蓝图, 入口, u.名)
    if (!支配者) continue

    // D3：最近支配单元本身就是选择单元 —— 上游次数由它说了算
    if (有.get(支配者)?.类型 === '选择') {
      出.push({
        码: 'D3',
        级别: '警',
        消息: `硬单元「${u.名}」的最近支配单元「${支配者}」是选择单元，上游次数不定`,
        位置: u.名,
      })
    }

    // D1：支配单元 → 这个硬单元 之间有没有「次数不定」的单元
    const 中间 = 之间(蓝图, 支配者, u.名)
    const 选择 = 中间.filter((n) => 有.get(n)?.类型 === '选择')
    if (选择.length) {
      出.push({
        码: 'D1',
        级别: '警',
        消息: `硬单元「${u.名}」的来路上有选择单元：${选择.join('、')}`,
        位置: u.名,
      })
    }
    const 软汇 = 中间.filter((n) => 有.get(n)?.类型 === '软' && 上层们(蓝图, n).length >= 2)
    if (软汇.length) {
      出.push({
        码: 'D1',
        级别: '警',
        消息: `硬单元「${u.名}」的来路上有多上游软单元：${软汇.join('、')}`,
        位置: u.名,
      })
    }

    // D2：之间的子蓝图里有没有「不同步」的
    if (读子图) {
      const 子图们 = 中间.filter((n) => 有.get(n)?.类型 === '子蓝图')
      for (const 名 of 子图们) {
        const 子 = 读子图(名)
        if (!子) {
          出.push({
            码: 'D2',
            级别: '警',
            消息: `硬单元「${u.名}」的来路上，子蓝图「${名}」的文件没了`,
            位置: 名,
          })
          continue
        }
        if (算同步性(子, 读子图) === 1) {
          出.push({
            码: 'D2',
            级别: '警',
            消息: `硬单元「${u.名}」的来路上，子蓝图「${名}」不同步`,
            位置: 名,
          })
        }
      }
    }
  }

  return 出
}

