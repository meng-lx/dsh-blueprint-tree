// E · 循环向量
// ═══════════════════════════════════════════════════════════

/**
 * 用户 2026-11-10 的用途 3（原话）：
 *   「循环和硬单元判断差不多，只不过没有找最近支配单元那一步，直接检测报 E1，E2」
 * 同一天又补一条：
 *   「循环加一条，两单元要是支配的关系」
 *   ⇒ 循环向量的两个端点（选择单元 A 和它指回的上游 O）必须满足「O 支配 A」
 *
 * 路径取 `O → A`（不含两端），因为循环向量那条边就是 A→O，
 * 换句话说「O 到 A 之间」正好就是这条回边跨过的那一段。
 */
export function 查循环(蓝图: 蓝图, 读子图?: (名: string) => 蓝图 | undefined): 问题[] {
  const 出: 问题[] = []
  const 入口 = 蓝图.开始
  const 有 = new Map((蓝图.单元 ?? []).map((u) => [u.名, u]))

  for (const u of 蓝图.单元 ?? []) {
    if (u.类型 !== '循环向量') continue

    const A = 上层们(蓝图, u.名)[0]
    const O = 真实下层(u)[0]

    // E0：形态不对（少了端点，或者不是选择单元发出来的）
    if (!A || !O) {
      出.push({
        码: 'E0',
        级别: '警',
        消息: `循环向量「${u.名}」必须有一个上游（选择单元）和一个下游（它指回的上游单元）`,
        位置: u.名,
      })
      continue
    }
    if (有.get(A)?.类型 !== '选择') {
      出.push({
        码: 'E0',
        级别: '警',
        消息: `循环向量「${u.名}」只能由选择单元发出，「${A}」是「${有.get(A)?.类型}」`,
        位置: u.名,
      })
      continue
    }
    if (!有.has(O)) {
      出.push({ 码: 'E0', 级别: '警', 消息: `循环向量「${u.名}」指向的「${O}」不存在`, 位置: u.名 })
      continue
    }

    // E4（用户 2026-11-25 定）：循环向量指回的目标只能是「软」或「子蓝图」。
    //   · 硬 / 选择：回边把它拉起后它还要等齐别的上游 ⇒ 容易整条链卡死；
    //   · 子蓝图：重新进子图的入口单元，入口是点火口、不读输入，不会卡。
    const 目标类型 = 有.get(O)?.类型
    if (目标类型 !== '软' && 目标类型 !== '子蓝图') {
      出.push({
        码: 'E4',
        级别: '错',
        消息: `循环向量「${u.名}」指回的「${O}」是「${目标类型}」，循环头只能是软单元或子蓝图`,
        位置: u.名,
      })
    }

    // E3：两端必须是支配关系（O 支配 A）
    if (入口 && !甲支配乙(蓝图, 入口, O, A)) {
      出.push({
        码: 'E3',
        级别: '警',
        消息: `循环向量「${u.名}」两端不是支配关系：「${O}」不支配「${A}」`,
        位置: u.名,
      })
    }

    // E1：O → A 之间有没有「次数不定」的单元
    const 中间 = 之间(蓝图, O, A)
    const 选择 = 中间.filter((n) => 有.get(n)?.类型 === '选择')
    if (选择.length) {
      出.push({
        码: 'E1',
        级别: '警',
        消息: `循环向量「${u.名}」跨过的路径上有选择单元：${选择.join('、')}`,
        位置: u.名,
      })
    }
    const 软汇 = 中间.filter((n) => 有.get(n)?.类型 === '软' && 上层们(蓝图, n).length >= 2)
    if (软汇.length) {
      出.push({
        码: 'E1',
        级别: '警',
        消息: `循环向量「${u.名}」跨过的路径上有多上游软单元：${软汇.join('、')}`,
        位置: u.名,
      })
    }

    // E2：之间的子蓝图不同步
    if (读子图) {
      const 子图们 = 中间.filter((n) => 有.get(n)?.类型 === '子蓝图')
      for (const 名 of 子图们) {
        const 子 = 读子图(名)
        if (!子) {
          出.push({
            码: 'E2',
            级别: '警',
            消息: `循环向量「${u.名}」的路径上，子蓝图「${名}」的文件没了`,
            位置: 名,
          })
          continue
        }
        if (算同步性(子, 读子图) === 1) {
          出.push({
            码: 'E2',
            级别: '警',
            消息: `循环向量「${u.名}」的路径上，子蓝图「${名}」不同步`,
            位置: 名,
          })
        }
      }
    }
  }

  return 出
}

// ═══════════════════════════════════════════════════════════
// 汇总（统一返回格式）
// ═══════════════════════════════════════════════════════════

/**
 * 把问题数组折成统一形状：
 *   { 错误数, 警告数, 行: ['错|A2|单元「甲」出现了 2 次', ...] }
 *
 * 行格式：级别|码|消息|位置（位置可缺）
 */
export function 汇总(问题: 问题[]): { 错误数: number; 警告数: number; 行: string[] } {
  const 错误数 = 问题.filter((p) => p.级别 === '错').length
  const 警告数 = 问题.length - 错误数
  const 行 = 问题.map((p) => [p.级别, p.码, p.消息, p.位置 ?? ''].join('|').replace(/\|+$/, ''))
  return { 错误数, 警告数, 行 }
}
