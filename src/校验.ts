/**
 * @param 是不是子蓝图  true = 这张图是子蓝图（不许有开始/结束类型，但必须有入口出口）
 */
export function 查锚点(蓝图: 蓝图, 是不是子蓝图: boolean): 问题[] {
  const 出: 问题[] = []
  const 单元们 = 蓝图.单元 ?? []
  const 名字集 = new Set(单元们.map((u) => u.名))

  const 开始们 = 单元们.filter((u) => u.类型 === '开始').map((u) => u.名)
  const 结束们 = 单元们.filter((u) => u.类型 === '结束').map((u) => u.名)

  if (!是不是子蓝图) {
    // C1 主蓝图：恰好一个「开始」类型
    if (开始们.length !== 1) {
      出.push({
        码: 'C1',
        级别: '错',
        消息: `主蓝图必须恰好有一个「开始」类型单元，现在 ${开始们.length} 个${开始们.length ? `：${开始们.join('、')}` : ''}`,
        位置: 开始们[0],
      })
    }
    // C2 主蓝图：恰好一个「结束」类型
    if (结束们.length !== 1) {
      出.push({
        码: 'C2',
        级别: '错',
        消息: `主蓝图必须恰好有一个「结束」类型单元，现在 ${结束们.length} 个${结束们.length ? `：${结束们.join('、')}` : ''}`,
        位置: 结束们[0],
      })
    }
    // C3 蓝图.开始 指向那个开始单元
    if (蓝图.开始 && !开始们.includes(蓝图.开始)) {
      出.push({
        码: 'C3',
        级别: '错',
        消息: `蓝图里的开始锚点「${蓝图.开始}」不是「开始」类型的单元`,
        位置: 蓝图.开始,
      })
    }
    if (!蓝图.开始 && 开始们.length === 1) {
      出.push({
        码: 'C3',
        级别: '警',
        消息: `蓝图里没写开始锚点，应该指向「${开始们[0]}」`,
        位置: 开始们[0],
      })
    }
    // C4 蓝图.结束 指向那个结束单元
    if (蓝图.结束 && !结束们.includes(蓝图.结束)) {
      出.push({
        码: 'C4',
        级别: '错',
        消息: `蓝图里的结束锚点「${蓝图.结束}」不是「结束」类型的单元`,
        位置: 蓝图.结束,
      })
    }
  } else {
    // C7 子蓝图不许有「开始」/「结束」类型（这两个全项目唯一）
    for (const 名 of [...开始们, ...结束们]) {
      出.push({
        码: 'C7',
        级别: '错',
        消息: `子蓝图里不许有「开始」/「结束」类型的单元（它们全项目唯一），「${名}」违规`,
        位置: 名,
      })
    }
    // C8 子蓝图必须有入口和出口（可以是同一个单元）
    if (!蓝图.开始) {
      出.push({ 码: 'C8', 级别: '错', 消息: '子蓝图没写入口（蓝图.开始）' })
    } else if (!名字集.has(蓝图.开始)) {
      出.push({ 码: 'C8', 级别: '错', 消息: `子蓝图的入口「${蓝图.开始}」不存在`, 位置: 蓝图.开始 })
    }
    if (!单元们.some((u) => 是出口(u))) {
      出.push({ 码: 'C8', 级别: '错', 消息: `子蓝图没有出口（没有任何单元的下层写 ${结束标记}）` })
    }
  }

  // 入口：蓝图.开始（两张图都用它）
  const 入口 = 蓝图.开始 && 名字集.has(蓝图.开始) ? 蓝图.开始 : undefined

  // C5 每个单元都能从起点走到
  if (入口) {
    const 到得了 = 从这走(入口, 单元们)
    for (const u of 单元们) {
      if (u.名 === 入口 || 到得了.has(u.名)) continue
      // 已经是断路状态的不用报（用户 m03542：报错/失效/废弃 算断路，它们本来就跑不了）
      if (断路状态.has(u.状态)) continue
      {
        出.push({
          码: 'C5',
          级别: '错',
          消息: `单元「${u.名}」从起点「${入口}」走不到`,
          位置: u.名,
        })
      }
    }
  }

  // C6 每个单元都能走到出口（下层里写了 $结束 的才算出口）
  const 反图 = new Map<string, string[]>()
  for (const u of 单元们) {
    for (const 下 of u.下层 ?? []) {
      if (下 === 结束标记) continue
      const 已有 = 反图.get(下)
      if (已有) 已有.push(u.名)
      else 反图.set(下, [u.名])
    }
  }
  const 出口们 = 单元们.filter((u) => 是出口(u)).map((u) => u.名)
  const 单元表 = new Map(单元们.map((u) => [u.名, u]))
  if (出口们.length) {
    const 走得到 = 反向可达(出口们, 反图, 单元表)
    for (const u of 单元们) {
      if (走得到.has(u.名)) continue
      // 已经是断路状态的不用报
      if (断路状态.has(u.状态)) continue
      {
        出.push({
          码: 'C6',
          级别: '错',
          消息: `单元「${u.名}」走不到出口（没有任何一条路走到 ${结束标记}）`,
          位置: u.名,
        })
      }
    }
  } else if (单元们.length) {
    出.push({ 码: 'C6', 级别: '错', 消息: `整张图没有任何出口（没有单元的下层写 ${结束标记}）` })
  }

  return 出
}

/**
 * 这个单元是不是「断路」—— 路走到这儿就断了，不再往下走。
 *
 * 用户 m03542：「报错 / 失效 / 废弃的单元算断路」
 */
export function 断路(u: 单元 | undefined): boolean {
  return !!u && (u.状态 === '报错' || u.状态 === '失效' || u.状态 === '废弃')
}

/** 从起点顺着下层能走到的所有单元（穿过 $结束 就停；断路单元不往下走） */
function 从这走(开始名: string, 单元们: 单元[]): Set<string> {
  const 表 = new Map(单元们.map((u) => [u.名, u]))
  const 到 = new Set<string>()
  const 队 = [开始名]
  while (队.length) {
    const 名 = 队.pop()!
    if (到.has(名)) continue
    到.add(名)
    // 断路单元：它自己算「到得了」，但它后面走不过去
    if (断路(表.get(名))) continue
    for (const 下 of 表.get(名)?.下层 ?? []) {
      if (下 === 结束标记 || 到.has(下) || !表.has(下)) continue
      队.push(下)
    }
  }
  return 到
}

/** 从出口往回走能到的所有单元（断路单元不往上走） */
function 反向可达(出口们: string[], 反图: Map<string, string[]>, 表: Map<string, 单元>): Set<string> {
  const 到 = new Set<string>()
  const 队 = [...出口们]
  while (队.length) {
    const 名 = 队.pop()!
    if (到.has(名)) continue
    到.add(名)
    if (断路(表.get(名))) continue
    for (const 上 of 反图.get(名) ?? []) {
      if (!到.has(上)) 队.push(上)
    }
  }
  return 到
}

