export function 查规模(蓝图: 蓝图, 限制: 限制配置): 问题[] {
  const 出: 问题[] = []
  const n = (蓝图.单元 ?? []).length

  // H1 单元数上限（0 = 不限；用户 2026-11-16「单元个数可以放开一些，但token限制不能放开」）
  if (限制.单元数 > 0 && n > 限制.单元数) {
    出.push({
      码: 'H1',
      级别: '错',
      消息: `单元太多了：${n} 个，上限 ${限制.单元数}`,
    })
  }

  // H2 token 上限（粗估：中文 1 字 ≈ 1 token，英文 4 字符 ≈ 1 token ⇒ 按 2 字符/token 算）
  const 长度 = JSON.stringify(蓝图, null, 2).length
  const 估算 = Math.ceil(长度 / 2)
  if (估算 > 限制.token) {
    出.push({
      码: 'H2',
      级别: '错',
      消息: `蓝图太大了：约 ${估算} token，上限 ${限制.token}`,
    })
  }

  return 出
}

