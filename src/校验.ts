export function 查连线(蓝图: 蓝图): 问题[] {
  const 出: 问题[] = []
  const 单元们 = 蓝图.单元 ?? []
  const 名字集 = new Set(单元们.map((u) => u.名))

  for (const u of 单元们) {
    // B0 文件里不该有 上层（派生字段，读的时候现算）
    if ((u as 单元 & { 上层?: unknown }).上层 !== undefined) {
      出.push({
        码: 'B0',
        级别: '警',
        消息: `单元「${u.名}」带着「上层」—— 它是现算的，文件里不该存`,
        位置: u.名,
      })
    }

    const 下层 = u.下层 ?? []

    // B1 下层里每个名字都存在（$结束 除外）
    for (const 下 of 下层) {
      if (下 === 结束标记) continue
      if (!名字集.has(下)) {
        出.push({
          码: 'B1',
          级别: '错',
          消息: `单元「${u.名}」的下层指向不存在的「${下}」`,
          位置: `${u.名}.下层`,
        })
      }
    }

    // B2 连自己 —— 允许，但命令层会把它改造成循环向量单元（用户 2026-11-11：
    // 「单元自己循环，循环头尾单元间无选择和多上游软单元（因为没有单元），
    //   这样循环只要从选择开始，就符合定义」）⇒ 这里只报「警」，不动它
    if (下层.includes(u.名)) {
      出.push({ 码: 'B2', 级别: '警', 消息: `单元「${u.名}」连到了自己`, 位置: `${u.名}.下层` })
    }

    // B3 下层里不能有重复名字 —— 命令层会自动去重，这里只报「警」
    const 见过 = new Set<string>()
    for (const 下 of 下层) {
      if (见过.has(下)) {
        出.push({
          码: 'B3',
          级别: '警',
          消息: `单元「${u.名}」的下层里「${下}」重复了`,
          位置: `${u.名}.下层`,
        })
      }
      见过.add(下)
    }
  }

  return 出
}

