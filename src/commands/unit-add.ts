/** 把参数里的值拆成字符串数组；不是数组返回 '不是数组' */
function 字符串数组(值: unknown): string[] | undefined | '不是数组' {
  if (值 === undefined || 值 === null) return undefined
  if (Array.isArray(值)) {
    if (值.some((x) => typeof x !== 'string')) return '不是数组'
    return 值 as string[]
  }
  if (typeof 值 === 'string') {
    const 净 = 值.split(',').map((x) => x.trim()).filter((x) => x.length > 0)
    return 净
  }
  return '不是数组'
}

/** 扁平写法：字段直接写在参数顶层（不套一层「单元」） */
function 扁平单元(参数: Record<string, unknown>): Record<string, unknown> | undefined {
  if (typeof 参数.名 !== 'string' || !参数.名.trim()) return undefined
  const u: Record<string, unknown> = { 名: 参数.名 }
  for (const 键 of ['类型', '标签', '状态', '功能'] as const) {
    if (参数[键] !== undefined) u[键] = 参数[键]
  }
  for (const 键 of ['上层', '下层'] as const) {
    if (参数[键] !== undefined) u[键] = 字符串数组(参数[键])
  }
  if (参数.坐标 !== undefined) {
    const n = (字符串数组(参数.坐标) as unknown[]).map(Number)
    if (n.length === 2 && n.every(Number.isFinite)) u.坐标 = n
  }
  return u
}

/** 按固定字段顺序重建，保证文件里的键顺序稳定（用户：文件中顺序固定） */
// ⚠️ 「上层」不写进文件 —— 用户 2026-11-10 定：它是派生字段，读的时候现算（见 src/路径.ts）
export function 规整单元(u: 单元): 单元 {
  const 出: 单元 = { 名: u.名, 类型: u.类型, 标签: u.标签, 状态: u.状态 }
  if (u.下层 && u.下层.length) 出.下层 = u.下层
  if (u.坐标) 出.坐标 = u.坐标
  if (u.功能 !== undefined) 出.功能 = u.功能
  return 出
}

