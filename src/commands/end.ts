// 用户 2026-11-15 原话：
//   「结束就是结束当前项目所有正在跑的,并清空待做池和共享参数」
//   「另外我建议做一个结束命令,供测试和AI或用户用」
//
// 难点：状态机在**正在跑的那个进程**里，而这个命令是**另一个进程**调的。
// ⇒ 只能靠文件当信号：往 运行记录.json 写 `要求结束: true`，
//   状态机每轮读一次（一个 stat，开销很小），读到就：
//     ① 清空待做池
//     ② 清空共享数据
//     ③ 返回「中止」（正在跑的 Promise 直接丢弃，不等待）
//
// ⚠️ 「先停运行的单元，再清空池子和参数」—— 顺序照用户说的来。
//    JS 单线程，同步函数一旦进去停不掉（用户 m04995 定了先不上 Worker），
//    所以「停」的实际含义是：不再等它，直接弃掉。

import type { 命令定义 } from '../commands.ts'
import { 成功 } from '../types.ts'
import { 定位项目 } from '../登记表.ts'
import { 在跑的项目, 在跑的运行, 有隔离任务 } from '../任务.ts'
import { 读运行记录, 写运行记录 } from '../运行记录.ts'

/**
 * 看「这个项目现在在跑哪一次」。
 *
 * 用户 m19572：停止要核对运行标识，那调用方得先能拿到标识。运行开始就分配了，
 * 但运行命令的响应要跑完才回来 —— 所以另给一个轻量查询，页面/外部先问再停。
 */
export const 运行状态: 命令定义 = {
  名: 'run.status',
  说明: '看这个项目现在有没有在跑、正在跑的是哪一次运行（停止时把 本次运行 带上即可核对）',
  中文: ['运行状态', '在跑什么'],
  执行(参数) {
    const 定 = 定位项目(参数)
    if (!定.ok) return 定
    const 项目名 = String(参数.项目 ?? '')
    const 记录 = 读运行记录(定.数据.项目目录)
    const 有任务 = 有隔离任务()
    return 成功({
      项目: 项目名,
      在跑: 有任务 && 在跑的项目() === 项目名,
      任务: 有任务 ? 在跑的项目() : '',
      本次运行: (有任务 && 在跑的项目() === 项目名 ? 在跑的运行() : '') || 记录.本次运行 || '',
      要求结束: 记录.要求结束 ?? false,
    })
  },
}

export const 结束运行: 命令定义 = {
  名: 'run.stop',
  说明: '让当前项目正在跑的那一次运行结束：清空待做池、清空共享数据',
  中文: ['结束', '停止运行', '结束运行', '叫停'],
  执行(参数) {
    const 定 = 定位项目(参数)
    if (!定.ok) return 定
    const 项目目录 = 定.数据.项目目录
    const 项目名 = String(参数.项目 ?? '')

    const 记录 = 读运行记录(项目目录)
    // 用户 m19432：停止请求必须绑定到「某一次运行」。
    // 没有在跑就不写任何东西 —— 否则下次重跑会被这个旧标记直接中止。
    const 本次 = 记录.本次运行
    if (!本次) {
      return 成功({ 项目: 项目名, 要求结束: false, 提示: '这个项目现在没有在跑，没有可停的运行' })
    }
    // 用户 m19572：请求里带了运行标识就要核对 —— 指向旧运行 r1 的迟到请求
    // 不能把正在跑的 r2 停掉，也不能写标记。
    const 要停的 = String((参数 as Record<string, unknown> | undefined)?.本次运行 ?? '').trim()
    if (要停的 && 要停的 !== 本次) {
      return 成功({
        项目: 项目名,
        要求结束: false,
        本次运行: 本次,
        提示: '请求停的那一次运行已经不在跑了（现在在跑的是另一次），没有可停的运行',
      })
    }
    if (记录.要求结束 === 本次) {
      return 成功({
        项目: 项目名,
        要求结束: true,
        本次运行: 本次,
        提示: '这一次运行的结束请求还没被状态机消费掉',
      })
    }

    写运行记录(项目目录, { ...记录, 要求结束: 本次 })
    return 成功({ 项目: 项目名, 要求结束: true, 本次运行: 本次 })
  },
}
