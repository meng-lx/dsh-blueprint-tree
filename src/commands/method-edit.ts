/** 去掉每行公共缩进 —— 从页面框里复制回来的文本通常带缩进，插方法时会再加一次 */
function 去公共缩进(文本: string): string {
  const 行 = 文本.replace(/\r\n/g, '\n').replace(/^\n+/, '').replace(/\s+$/, '').split('\n')
  let 最少 = Infinity
  for (const l of 行) {
    if (!l.trim()) continue
    const n = l.length - l.replace(/^[ \t]+/, '').length
    if (n < 最少) 最少 = n
  }
  if (!Number.isFinite(最少) || 最少 === 0) return 行.join('\n')
  return 行.map((l) => (l.trim() ? l.slice(最少) : '')).join('\n')
}

/** 正文 → 整段方法。整段已经带骨架标记就原样用，否则当正文套进骨架 */
function 组全文(文本: string, 单元名: string, 骨架文本: string): string {
  if (文本.includes('/*从这里开始***')) return 文本
  const 行 = 骨架文本.split('\n')
  const 起 = 行.findIndex((l) => l.trim() === '/*从这里开始***/')
  if (起 < 0) return 骨架文本
  // 标记行后紧跟的 `return {};` 是占位，正文要替代它
  let 尾 = 起 + 1
  if (行[尾]?.trim() === 'return {};') 尾++
  const 正文行 = 文本
    .replace(/\s+$/, '')
    .split('\n')
    .map((l) => (l.trim() ? '        ' + l.trimEnd() : ''))
  return [...行.slice(0, 起 + 1), ...正文行, ...行.slice(尾)].join('\n')
}

export const 写方法: 命令定义 = {
  名: 'method.write',
  说明: '把一段方法源码写回方法文件（旧版本按规则进历史）；整段方法或只写正文都行',
  中文: ['写方法', '保存方法', '存方法', '方法写回'],
  执行(参数) {
    const 位 = 定位(参数)
    if (!位.ok) return 位
    const { 项目目录, 配置, 蓝图名, 蓝图, 方法文件, 历史文件 } = 位.数据

    const 名 = String(参数.单元 ?? '').trim()
    if (!名) return 失败('参数', '缺少「单元」——写哪个单元的方法', '单元')
    const u = 蓝图.单元.find((x) => x.名 === 名)
    if (!u) return 失败('不存在', `蓝图「${蓝图名}」里没有单元「${名}」`, 名)

    const 原文 = String(参数.方法 ?? '')
    // 用户 2026-11-22：方法要能保存空值 —— 但**不能删**（单元强制绑定方法）。
    // 空正文 = 把方法重置成插件骨架（只有头 + 取数行 + 占位 return {}），旧版本照规矩进历史
    if (!原文.trim()) {
      const 骨架文本 = 骨架(蓝图, 名, 方法文件)
      const 上限 = Number(参数.历史个数 ?? 配置.方法.历史个数 ?? 默认历史个数)
      const 一条 = 写单元方法(
        { 项目目录, 配置, 蓝图名, 蓝图, 方法文件, 历史文件 },
        名,
        骨架文本,
        上限,
      )
      if (!一条.ok) return 失败(一条.错误.类型, 一条.错误.消息, 一条.错误.位置)
      const 当前 = 读方法文件(方法文件, 蓝图名, false).源码
      const 块 = 切方法(当前, 名, 当前变量名)
      return 成功({
        蓝图: 蓝图名,
        单元: 名,
        方法: 块 ? 块.文本 : 一条.全文,
        已重置: true,
        ...(一条.进历史 ? { 进历史: 一条.进历史 } : {}),
        总方法数: 列出方法(当前, 当前变量名).length,
      })
    }

    const 全文 = 组全文(去公共缩进(原文), 名, 骨架(蓝图, 名, 方法文件))
    const 上限 = Number(参数.历史个数 ?? 配置.方法.历史个数 ?? 默认历史个数)
    const 一条 = 写单元方法(
      { 项目目录, 配置, 蓝图名, 蓝图, 方法文件, 历史文件 },
      名,
      全文,
      上限,
    )
    if (!一条.ok) return 失败(一条.错误.类型, 一条.错误.消息, 一条.错误.位置)

    // 回一份「现在文件里这一段长什么样」，页面不用再请求一次
    const 当前 = 读方法文件(方法文件, 蓝图名, false).源码
    const 块 = 切方法(当前, 名, 当前变量名)

    return 成功({
      蓝图: 蓝图名,
      单元: 名,
      方法: 块 ? 块.文本 : 一条.全文,
      ...(一条.进历史 ? { 进历史: 一条.进历史 } : {}),
      ...(一条.提醒 ? { 提醒下游: 一条.提醒 } : {}),
      总方法数: 列出方法(当前, 当前变量名).length,
    })
  },
}
