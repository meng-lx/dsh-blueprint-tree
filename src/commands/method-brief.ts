// method.brief —— 把一个单元「写方法需要知道的一切」一次性交给 AI
//
// 用户 m14357：「ai在处理一个单元时,是不是需要直接上游单元的功能描述,加上知道程序自动
// 生成了什么,这样才能知道有什么可用信息用于完成当前单元功能……要做一个输入一个指令,
// 返回一段信息(直接上游功能和输出了什么的文字说明,当前单元要做什么,程序声称了什么框架
// 并指明要填的地方)」
//
// 所以这里只读不写：给一段可以直接贴给模型看的话。
// 框架那段和 `method.write` 生成的一模一样（同一个 骨架() 函数），
// 模型照着填完，再把正文交回 `method.write` 即可。

import type { 命令定义 } from '../commands.ts'
import { 成功, 失败 } from '../types.ts'
import { 定位, 读方法文件, 当前变量名, 上层们, 骨架 } from '../方法命令.ts'
import { 切方法 } from '../方法文件.ts'
import { 推断输出表, 被读字段 } from '../方法类型.ts'

/** 字段表 → `a: number; b: string` */
function 字段串(表: Record<string, string> | undefined): string {
  if (!表) return ''
  const 段 = Object.entries(表).map(([名, 型]) => `${名}: ${型}`)
  return 段.join('；')
}

export const 方法说明: 命令定义 = {
  名: 'method.brief',
  说明: '给 AI 用：一个单元要写方法所需的全部上下文（上游功能与输出字段、当前单元要做什么、插件生成的框架、要填的地方、下游读什么）',
  中文: ['方法说明', '取方法说明', '单元说明', '看方法说明', '说明方法'],
  执行(参数) {
    const 位 = 定位(参数)
    if (!位.ok) return 位
    const { 配置, 蓝图名, 蓝图, 方法文件 } = 位.数据

    const 名 = String(参数.单元 ?? '').trim()
    if (!名) return 失败('参数', '缺少「单元」——要说明哪个单元', '单元')
    const u = 蓝图.单元.find((x) => x.名 === 名)
    if (!u) return 失败('不存在', `蓝图「${蓝图名}」里没有单元「${名}」`, 名)

    const 方法 = 读方法文件(方法文件, 蓝图名, false).源码
    const 输出们 = 推断输出表(方法, 蓝图名 + '.方法.ts')
    const 上层 = 上层们(蓝图, 名)
    const 下层 = (u.下层 ?? []).filter((x) => x !== '$结束' && x !== '')
    const 行: string[] = []

    行.push(`【单元】${蓝图名} · ${名}`)
    行.push(`功能：${String(u.功能 ?? '').trim() || '（还没写功能说明 —— 先用 unit.update 补上）'}`)
    行.push(`类型：${String(u.类型 ?? '软')}　　标签：${String(u.标签 ?? '无')}　　状态：${String(u.状态 ?? '正常')}`)
    if (u.类型 === '选择') {
      行.push(`它是「选择」单元：靠返回的 Start_<下游名>: boolean 决定往下走哪条`)
    }
    行.push('')

    行.push(`【直接上游】${上层.length ? '数据从「输入」数组里按来源名取' : '（没有上游：这个单元从开始单元直接拿点火数据）'}`)
    if (上层.length) {
      for (const 上 of 上层) {
        const 上单元 = 蓝图.单元.find((x) => x.名 === 上)
        const 表 = 输出们[上]
        行.push(`- ${上}（${String(上单元?.类型 ?? '?')}，状态 ${String(上单元?.状态 ?? '?')}）`)
        行.push(`  功能：${String(上单元?.功能 ?? '').trim() || '（没写）'}`)
        行.push(`  返回字段：${表 && Object.keys(表).length ? 字段串(表) : '（这个上游还没有方法，字段只能当 Record<string, unknown> 用）'}`)
      }
    }
    行.push('')

    行.push('【插件生成的框架】（下面这段是插件写的，能看不能改；取数行已经把上游字段类型写好了）')
    行.push('```ts')
    行.push(骨架(蓝图, 名, 方法文件))
    行.push('```')
    行.push('')

    行.push('【你要填的地方】`/*从这里开始***/` 这一行之后，直到方法结束之前')
    行.push('- 最后一行必须是 `return { 字段: 变量, ... };`（插件只解析这一行，中间不要有别的 return）')
    行.push('- 每个变量都要写成 `const 名字: 类型 = ...`（G4 检查会拦没有类型标注的变量）')
    行.push('- 返回值只能是**平坦记录**：字段值只允许 string / boolean / 有限的 number；`undefined` 字段当作省略，不能返回 null / 数组 / 嵌套对象 / Map / Set / Date / 函数 / symbol / bigint / NaN / Infinity。要传结构就自己编码成字符串（例如 `JSON.stringify(...)`），下游按约定还原')
    if (u.类型 === '选择') 行.push(`- 还要返回 Start_<下游名>: boolean，决定往下走哪条；这个单元的下游：${下层.length ? 下层.join('、') : '（没有下游）'}`)
    行.push('')

    行.push('【下游】它们会读你的输出')
    let 有下游 = false
    for (const 下 of 下层) {
      const 本格读 = 读字段Of下游(方法, 名, 下)
      行.push(`- ${下}${本格读.length ? `：读你的字段 ${本格读.join('、')}` : '：（还没写方法，或者还没用到你的字段）'}`)
      有下游 = true
    }
    if (!有下游) 行.push('- （没有下游）')
    行.push('')

    const 块 = 切方法(方法, 名, 当前变量名)
    行.push('【现在的方法】' + (块 ? '' : '（还没有方法 —— 插件会按上层自动生成一个只有取数行的空方法）'))
    if (块) {
      行.push('```ts')
      行.push(块.文本.trim())
      行.push('```')
    }

    const 文字 = 行.join('\n')
    return 成功({
      文字,
      项目: String(配置.项目名 ?? ''),
      蓝图: 蓝图名,
      单元: 名,
      上层,
      下游: 下层,
      输出: 输出们[名] ?? {},
    })
  },
}

/**
 * 下游方法里读「本单元」的那些字段。
 * 直接扫下游方法文本里的 `上游_<本单元>` 契约块。
 */
function 读字段Of下游(方法: string, 本单元: string, 下游: string): string[] {
  const 块 = 切方法(方法, 下游, 当前变量名)
  if (!块) return []
  return 被读字段(块.文本, 本单元)
}
