// page.refresh —— 让界面刷新当前页面
// page.signal  —— 界面轮询用：读刷新序号（不改变它）
//
// 用户 2026-11-18：「页面是自动刷新的吗，不是就给自动排列下面加个刷新按钮，
// 再加一个给ai用的指令，刷新是刷新当前页面，切换页面时自动刷新」
// ⇒ 人点按钮、AI 调命令，走同一条路：命令把序号 +1，前端每 2.5 秒问一次 signal，
//    序号变了就重读当前页面（项目页重读项目列表，蓝图页重读图）。
//
// 这两个是界面自检命令，不进蓝图链路（控制器对 page.* 直接走 TS），
// 原因是刷新属于「界面动作」，没有业务语义，塞进链路只会让另一边的校验和测试都跟着变。

import type { 结果 } from '../types.ts'
import { 成功 } from '../types.ts'
import type { 命令定义 } from '../commands.ts'

/** 进程内单调递增：DSH 进程重启后归零，前端以首次读到的值作为基准 */
let 刷新序号 = 0

export const 刷新页面: 命令定义 = {
  名: 'page.refresh',
  说明: '让插件界面刷新当前页面（项目页重读项目列表，蓝图页重读当前蓝图）；人和 AI 都调这个',
  中文: ['刷新页面', '刷新', '重读页面'],
  执行(参数: Record<string, unknown>): 结果 {
    刷新序号 += 1
    return 成功({
      序号: 刷新序号,
      页面: String(参数?.页面 ?? ''),
      项目: String(参数?.项目 ?? ''),
      蓝图: String(参数?.蓝图 ?? ''),
    })
  },
}

export const 读刷新: 命令定义 = {
  名: 'page.signal',
  说明: '界面轮询用：读当前刷新序号（不改变它）',
  中文: ['刷新信号'],
  执行(): 结果 {
    return 成功({ 序号: 刷新序号 })
  },
}
