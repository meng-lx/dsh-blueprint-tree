// 用户 2026-11-07：文件名等设置只在插件里写死，建项目时不开放调整参数。
// 用户 2026-11-10：**建完要把路径写进登记表**，之后所有命令只认项目名 ——
//                  所以这里返回的结果里也不再出现路径（AI 拿不到具体位置）。

import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import type { 结果 } from '../types.ts'
import { 成功, 失败 } from '../types.ts'
import type { 命令定义 } from '../commands.ts'
import { 第一层默认配置, 写配置, 产物文件名 } from '../项目.ts'
import { 空方法文件 } from '../方法命令.ts'
import { 查项目, 登记 } from '../登记表.ts'

function 蓝图模板(蓝图名: string, 带锚点 = true): string {
  // 新建项目就带两个锚点单元，画布至少有内容、也能直接运行
  // （用户 2026-11-15：「新建项目时自动加入一个 开始（类型=开始）
  //   和一个 结束（类型=结束）」）
  // ⚠️ 两个**不连起来**（用户同一句：「但不连起来」）—— 开始的下层是空的。
  //    结束的下层写 `$结束`，那是「走到这里就结束」的出口标记，不是连向别的单元。
  const 数据 = {
    格式版本: 1,
    名: 蓝图名,
    开始: 带锚点 ? '开始' : null,
    结束: 带锚点 ? '结束' : null,
    同步性: 0,
    单元: 带锚点
      ? [
          { 名: '开始', 类型: '开始', 标签: '无', 状态: '提醒' },
          { 名: '结束', 类型: '结束', 标签: '无', 状态: '提醒', 下层: ['$结束'] },
        ]
      : [],
  }
  return JSON.stringify(数据, null, 2) + '\n'
}

export const 建项目: 命令定义 = {
  名: 'project.create',
  说明: '创建项目并登记。登记之后所有命令只认「项目」名，不再需要路径',
  中文: ['创建项目', '新建项目', '建项目', '新项目', '初始化项目'],
  执行(参数): 结果 {
    const 父 = String(参数.路径 ?? '').trim()
    const 名 = String(参数.名 ?? '').trim()
    const 蓝图名 = String(参数.蓝图名 ?? '主蓝图').trim()

    if (!名) return 失败('参数', '缺少「名」——项目叫什么', '名')
    if (!蓝图名) return 失败('参数', '「蓝图名」不能为空', '蓝图名')

    // 没给路径就用默认目录（界面上写的就是「留空 = 默认测试目录」）
    const 根 = 父 || path.join(os.tmpdir(), 'blueprint-tree-项目')
    const 项目目录 = path.resolve(根, 名)

    if (fs.existsSync(项目目录)) {
      return 失败('已存在', `目录已存在，不覆盖：${项目目录}`, 项目目录)
    }

    // 设置全部来自第 1 层（插件里写死），不接受调用方覆盖
    const 配置 = 第一层默认配置(名)
    配置.蓝图.默认名 = 蓝图名

    fs.mkdirSync(项目目录, { recursive: true })
    写配置(项目目录, 配置)

    const 文件 = 产物文件名(配置, 蓝图名)
    const 蓝图文件 = path.join(项目目录, 文件.蓝图)
    const 方法文件 = path.join(项目目录, 文件.方法)
    const 历史文件 = path.join(项目目录, 文件.方法历史)

    // 防御：万一以后默认值被改坏，三个名字撞车会互相覆盖
    if (蓝图文件 === 方法文件 || 蓝图文件 === 历史文件 || 方法文件 === 历史文件) {
      return 失败('参数', '三个产物文件名撞车了，会互相覆盖', '文件名')
    }

    // 锚点单元：默认带（界面/用户新建项目就有内容）；测试传「锚点: false」拿空图
    fs.writeFileSync(蓝图文件, 蓝图模板(蓝图名, 参数.锚点 !== false), 'utf8')
    fs.writeFileSync(方法文件, 空方法文件(蓝图名, false), 'utf8')
    fs.writeFileSync(历史文件, 空方法文件(蓝图名, true), 'utf8')
    // 锚点单元也先补上方法骨架（开始/结束各一个空方法）
    try { 同步方法文件(项目目录, 配置, 蓝图名, JSON.parse(蓝图模板(蓝图名, 参数.锚点 !== false)) as never) } catch { }

    // 登记 —— 之后所有命令靠这个名字找目录（重名直接覆盖，重名检测以后交给检测功能）
    登记(名, { 路径: 项目目录, 蓝图: 蓝图名, 创建于: new Date().toISOString() })

    // ⚠️ 返回里**不给路径** —— 用户 2026-11-10 的要求
    return 成功({
      项目: 名,
      蓝图: 蓝图名,
      文件: [文件.蓝图, 文件.方法, 文件.方法历史],
    })
  },
}
