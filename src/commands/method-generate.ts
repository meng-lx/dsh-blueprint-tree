export type 生成结果 =
  | { ok: true; 全文: string; 进历史?: string; 提醒?: string[] }
  | { ok: false; 错误: 错误信息 }

function 出错(
  类型: 错误信息['类型'],
  消息: string,
  位置?: string | string[],
): { ok: false; 错误: 错误信息 } {
  return { ok: false, 错误: { 类型, 消息, 位置 } }
}

/**
 * 给一个单元生成方法并写盘。
 *
 * 用户 m07665：「这个功能在没方法时自动启用就行」⇒ 运行方法直接调它，
 * 不需要人先敲 `method.generate`。
 */
export async function 生成单元方法(
  位: 生成输入,
  单元名: string,
  历史上限: number,
): Promise<生成结果> {
  const u = 位.蓝图.单元.find((x) => x.名 === 单元名)
  if (!u) {
    return 出错('不存在', `蓝图「${位.蓝图名}」里没有单元「${单元名}」`, 单元名)
  }
  // 没有说明就没法让 AI 写 —— 直接说清楚，别凭空猜
  if (!单元说明(u)) {
    return 出错('校验', `单元「${单元名}」没有「功能」说明，AI 无从下手（先用 unit.update 填功能）`, 单元名)
  }
  if (!有AI()) {
    return 出错('校验', 'AI 没接上：Host 半边的 llm 服务不可用（重启 DSH 试试）', 'AI')
  }

  let 正文 = ''
  try {
    正文 = 去围栏(await 问AI(系统提示, 用户提示(位.蓝图, 位.蓝图名, u)))
  } catch (e) {
    return 出错('IO', `AI 生成「${单元名}」失败：${e instanceof Error ? e.message : String(e)}`, 单元名)
  }
  if (!正文.trim()) {
    return 出错('IO', `AI 对「${单元名}」返回了空内容`, 单元名)
  }

  const 全文 = 套进骨架(骨架(位.蓝图, 单元名, 位.方法文件), 正文)
  return 写单元方法(位, 单元名, 全文, 历史上限)
}

/**
 * 把一段**已经写好**的方法全文落盘：旧方法进历史 → 插新的 → 裁历史 → 跑检查 → 写两个文件。
 * `method.generate` 与页面上的「编辑方法」共用这一套，保证两条路写出来的东西一模一样。
 */

export function 写单元方法(
  位: 生成输入,
  单元名: string,
  全文: string,
  历史上限: number,
): 生成结果 {
  let 当前 = 读方法文件(位.方法文件, 位.蓝图名, false).源码
  let 历史 = 读方法文件(位.历史文件, 位.蓝图名, true).源码
  const 旧源码 = 当前

  // 同名旧方法 ⇒ 加时间戳挪进历史
  let 进历史: string | undefined
  if (切方法(当前, 单元名, 当前变量名)) {
    const 键 = 唯一历史键(历史, 单元名)
    const 搬 = 搬进历史(当前, 历史, 单元名, 键)
    if (搬) {
      当前 = 搬.当前
      历史 = 搬.历史
      进历史 = 键
    }
  }

  const 插 = 插方法(当前, 全文, 当前变量名)
  if (!插.插了) {
    return 出错('校验', `写不进方法文件：${位.方法文件}`, 位.方法文件)
  }
  当前 = 插.源码
  const 裁 = 裁历史(历史, 历史上限)

  // 先检查再落盘：检查不过就一个字节都不写
  const 检查 = 跑检查('method.create', {
    蓝图: 位.蓝图,
    蓝图名: 位.蓝图名,
    是不是子蓝图: 位.蓝图名 !== 位.配置.蓝图.默认名,
    方法源码: 当前,
    历史源码: 裁.源码,
    限制: 位.配置.限制,
  })
  if (检查.拦.length) {
    return 出错('校验', 拦的消息(检查.拦), 检查.拦[0].码)
  }

  fs.writeFileSync(位.方法文件, 当前, 'utf8')
  fs.writeFileSync(位.历史文件, 裁.源码, 'utf8')

  // 方法一改，下游骨架的取数行就得跟着重算（正文保留）；文本真变了才标「提醒」
  const 同 = 重生成({ ...位, 蓝图: 位.蓝图 }, 下游们(位.蓝图, 单元名))

  return {
    ok: true,
    全文,
    ...(进历史 ? { 进历史 } : {}),
    ...(同.改了.length ? { 改动下游: 同.改了 } : {}),
    ...(同.提醒.length ? { 提醒: 同.提醒 } : {}),
  }
}

