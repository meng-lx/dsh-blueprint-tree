function 单元说明(u: 单元): string {
  return typeof u.功能 === 'string' && u.功能.trim() ? u.功能.trim() : ''
}

/** 和 方法骨架 里一致的变量名（含重名加 _2 的规则） */
function 上游变量们(蓝图: 蓝图, 单元名: string): { 名: string; 变量: string }[] {
  const 出: { 名: string; 变量: string }[] = []
  const 用过 = new Set<string>()
  for (const 上 of 上层们(蓝图, 单元名)) {
    let 变量 = '上游_' + String(上).replace(/[^\p{L}\p{N}_$]/gu, '_')
    if (用过.has(变量)) {
      let i = 2
      while (用过.has(`${变量}_${i}`)) i++
      变量 = `${变量}_${i}`
    }
    用过.add(变量)
    出.push({ 名: 上, 变量 })
  }
  return 出
}

function 用户提示(蓝图: 蓝图, 蓝图名: string, u: 单元): string {
  const 行: string[] = []
  行.push(`蓝图：${蓝图名}`)
  行.push(`单元：${u.名}（类型 ${u.类型}，标签 ${u.标签}）`)
  行.push('')
  行.push('单元说明（用户写的功能描述，按它实现）：')
  行.push(单元说明(u) || '（没写说明）')

  const 上 = 上游变量们(蓝图, u.名)
  行.push('')
  if (上.length) {
    行.push('上游单元（它们的输出就是你的输入）：')
    for (const { 名, 变量 } of 上) {
      const 上单元 = (蓝图.单元 ?? []).find((x) => x.名 === 名)
      const 说明 = 上单元 ? 单元说明(上单元) : ''
      行.push(`- ${名} → 变量 ${变量}${说明 ? `；它的功能：${说明}` : ''}`)
    }
  } else {
    行.push('上游单元：无（这个单元是入口，输入数组是空的）')
  }

  const 下 = (u.下层 ?? []).filter((x) => x !== '$结束')
  if (下.length) {
    行.push('')
    行.push(`下游单元（你把结果写进 return，它们会拿到）：${下.join('、')}`)
  }

  if (u.类型 === '选择') {
    行.push('')
    行.push(
      '这是选择单元：额外用 `Start_<下游单元名>: true/false` 决定要不要调起某个下游，' +
        '例如 `return { Start_甲: true, Start_乙: false, 结果: 值 };`。',
    )
  }

  行.push('')
  行.push('现在只输出方法体（从这里开始到 return 那一段），不要围栏、不要解释。')
  return 行.join('\n')
}

/** 去掉模型爱加的 ``` 围栏 */
function 去围栏(文本: string): string {
  let 净 = String(文本 ?? '').replace(/\r\n/g, '\n').trim()
  const 围 = /^```[^\n]*\n([\s\S]*?)\n```$/.exec(净)
  if (围) 净 = 围[1].trim()
  return 净
}

/** 把骨架里的占位 `return {};` 换成 AI 的正文（整体缩进 8 格） */
function 套进骨架(骨架文本: string, 正文: string): string {
  const 行 = 骨架文本.split('\n')
  const 起 = 行.findIndex((l) => l.trim() === '/*从这里开始***/' || l.trim() === '/*从这里开始***')
  if (起 < 0) return 骨架文本

  // 旧格式：起止标记之间整段是注释区，替换它们之间的行
  const 止 = 行.findIndex((l, i) => i > 起 && l.trim() === '*/')
  const 正文行 = 正文
    .split('\n')
    .map((l) => (l.trim() ? '        ' + l.trimEnd() : l))

  if (止 > 起) return [...行.slice(0, 起 + 1), ...正文行, ...行.slice(止)].join('\n')

  // 新格式：标记行后紧跟占位 `return {};`，把它换掉
  let 尾 = 起 + 1
  if (行[尾]?.trim() === 'return {};') 尾++
  return [...行.slice(0, 起 + 1), ...正文行, ...行.slice(尾)].join('\n')
}

