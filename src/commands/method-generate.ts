export const 生成方法: 命令定义 = {
  名: 'method.generate',
  说明:
    '单元没有方法时，用单元的「功能」说明让 AI 写一段方法（走 DSH 自己的模型，不配 API key）；返回生成的长字符串全文',
  中文: ['生成方法', 'ai写方法', '用ai写方法', '补方法', '生成单元方法', '自动写方法'],
  async 执行(参数) {
    const 位 = 定位(参数)
    if (!位.ok) return 位
    const { 配置, 蓝图名, 蓝图, 方法文件, 历史文件 } = 位.数据

    // ① 收单元名
    const 原始 = 参数.单元
    const 名单 = (
      Array.isArray(原始) ? 原始.map((x) => String(x)) : 原始 === undefined ? [] : [String(原始)]
    )
      .map((x) => x.trim())
      .filter((x) => x.length > 0)
    if (!名单.length) {
      return 失败('参数', '缺少「单元」——给哪个单元写方法（也可以直接写 单元=名字）', '单元')
    }

    const 缺 = 名单.filter((名) => !蓝图.单元.some((u) => u.名 === 名))
    if (缺.length) {
      return 失败('不存在', `蓝图「${蓝图名}」里没有这些单元：${缺.join('、')}`, 缺.join('、'))
    }

    const 上限 = Number(参数.历史个数 ?? 配置.方法.历史个数 ?? 默认历史个数)
    const 生成输入: 生成输入 = { 项目目录: 位.数据.项目目录, 配置, 蓝图名, 蓝图, 方法文件, 历史文件 }

    // ② 逐个问、逐个写
    const 进历史: string[] = []
    const 提醒: string[] = []
    const 写的: { 单元: string; 方法: string }[] = []
    for (const 名 of 名单) {
      const 一条 = await 生成单元方法(生成输入, 名, 上限)
      if (!一条.ok) return 失败(一条.错误.类型, 一条.错误.消息, 一条.错误.位置)
      写的.push({ 单元: 名, 方法: 一条.全文 })
      if (一条.进历史) 进历史.push(一条.进历史)
      if (一条.提醒) 提醒.push(...一条.提醒)
    }

    const 当前 = 读方法文件(方法文件, 蓝图名, false).源码
    const 检查 = 跑检查('method.create', {
      蓝图,
      蓝图名,
      是不是子蓝图: 蓝图名 !== 配置.蓝图.默认名,
      方法源码: 当前,
      历史源码: 读方法文件(历史文件, 蓝图名, true).源码,
      限制: 配置.限制,
    })

    return 成功({
      蓝图: 蓝图名,
      生成: 写的.map((w) => w.单元),
      // ← 用户要的「长字符串全塞进去」：每段方法原样返回
      方法: 写的.map((w) => w.方法).join('\n\n'),
      ...(进历史.length ? { 进历史 } : {}),
      ...(提醒.length ? { 提醒下游: 提醒 } : {}),
      ...(检查.改.length ? { 方法无效: 检查.改.map((p) => `${p.码}|${p.消息}`) } : {}),
      总方法数: 列出方法(当前, 当前变量名).length,
    })
  },
}
