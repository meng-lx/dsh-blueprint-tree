// method.restore —— 把方法退回上一个版本
//
// 用户 2026-11-10：「还原是删除现有对应名称方法（如果有）并把最近时间戳的方法的时间戳去掉」
//
// 步骤：① 当前有同名方法 ⇒ 删掉（不保留，用户定的「直接删除」）
//       ② 历史里挑时间戳最大的「名#...」⇒ 去掉时间戳挪回当前

import fs from 'node:fs'
import type { 命令定义 } from '../commands.ts'
import { 成功, 失败 } from '../types.ts'
import { 定位, 读方法文件, 当前变量名, 历史变量名, 分隔符 } from '../方法命令.ts'
import { 列出方法, 切方法, 删方法, 插方法, 改键 } from '../方法文件.ts'
import { 跑检查, 拦的消息 } from '../跑检查.ts'
import { 重生成, 下游们, 同步方法文件 } from '../方法同步.ts'

export const 还原方法: 命令定义 = {
  名: 'method.restore',
  说明: '把方法退回上一个版本（删掉现在的，把历史里最近那条挪回来）；用「蓝图」指定哪个蓝图/子蓝图',
  中文: ['还原方法', '恢复方法', '回退方法', '退回方法'],
  执行(参数) {
    const 位 = 定位(参数)
    if (!位.ok) return 位
    const { 蓝图名, 方法文件, 历史文件 } = 位.数据

    const 名 = String(参数.单元 ?? '').trim()
    if (!名) return 失败('参数', '缺少「单元」——还原哪个方法', '单元')

    let 当前 = 读方法文件(方法文件, 蓝图名, false).源码
    let 历史 = 读方法文件(历史文件, 蓝图名, true).源码

    // ① 历史里所有「名#...」（注意前缀要连 # 一起比，否则 名=单元1 会撞上 单元10#...）
    const 候选 = 列出方法(历史, 历史变量名)
      .filter((k) => k.startsWith(名 + 分隔符))
      .sort()
    if (!候选.length) return 失败('不存在', `历史里没有「${名}」的旧版本`, 名)
    const 键 = 候选[候选.length - 1] // 字典序最大 == 时间最近

    // ② 删掉现在这个（如果有）
    const 删 = 删方法(当前, 名, 当前变量名)
    当前 = 删.源码

    // ③ 历史那条去掉时间戳，挪回当前
    const 改 = 改键(历史, 键, 名, 历史变量名)
    if (!改.改了) return 失败('校验', `历史里「${键}」改不回原名`, 键)
    const 新块 = 切方法(改.源码, 名, 历史变量名)
    if (!新块) return 失败('校验', `历史里「${键}」切不出来`, 键)

    const 插 = 插方法(当前, 新块.文本, 当前变量名)
    if (!插.插了) return 失败('校验', `写不进方法文件：${方法文件}`, 方法文件)
    当前 = 插.源码
    历史 = 删方法(改.源码, 名, 历史变量名).源码

    fs.writeFileSync(方法文件, 当前, 'utf8')
    fs.writeFileSync(历史文件, 历史, 'utf8')

    // ④ 检查（表里 method.restore：A1 拦；G1/G3 是「可保存但不会执行」⇒ 只提示，不拦）
    let 方法提示: string[] = []
    try {
      const 检查 = 跑检查('method.restore', {
        蓝图: { 格式版本: 1, 名: 蓝图名, 开始: null, 结束: null, 同步性: 0, 单元: [] },
        蓝图名,
        是不是子蓝图: false,
        方法源码: 当前,
        历史源码: 历史,
      })
      方法提示 = 检查.改.map((p) => `${p.码}|${p.消息}`)
    } catch {
      // 检查坏了不该拦住还原
    }

    // 方法退回去了，下游骨架的取数行要跟着重算
    const 同 = 同步方法文件(位.数据.项目目录, 位.数据.配置, 蓝图名, 位.数据.蓝图)

    return 成功({
      蓝图: 蓝图名,
      单元: 名,
      还原自: 键,
      删掉了现在的版本: 删.删了,
      ...(方法提示.length ? { 方法提示 } : {}),
      ...(同.改了.length ? { 改动下游: 同.改了 } : {}),
      ...(同.提醒.length ? { 提醒下游: 同.提醒 } : {}),
    })
  },
}
