// 项目配置 —— 设置分三层（用户 2026-11-07 定）
//
//   1. 项目默认配置   开发时写死，**没有任何命令能改**   ★ 目前只做这一层
//   2. 用户全局配置   可设置项比 1 少，暂不存在
//   3. 项目设置       可设置项更少，打开这个项目时优先级最高（项目里的 flow.json）
//
// 合并顺序：1 ← 2 ← 3，后面的覆盖前面的。
// 现在 2、3 层都还没开放，实际生效的就是第 1 层写死的值。

import fs from 'node:fs'
import path from 'node:path'

/** 配置文件的固定名字（这个本身不参与配置，否则自指） */
export const 配置文件名 = 'flow.json'

export interface 产物配置 {
  /** 文件名模板：{名} = 蓝图名，{项目} = 项目名 */
  文件: string
}

/** 规模限制（用户 2026-11-10：「规模和单元个数的限制放在设置 json 里」） */
export interface 限制配置 {
  /** 一个蓝图最多几个单元 */
  单元数: number
  /** 一个蓝图最多多少 token（300000 = 300K） */
  token: number
}

export interface 项目配置 {
  格式版本: number
  项目名: string
  蓝图: 产物配置 & { 默认名: string }
  /** 历史个数：同一个单元最多留几个旧版本（用户 2026-11-10：这是设置项） */
  方法: 产物配置 & { 历史个数: number }
  方法历史: 产物配置
  限制: 限制配置
}

// ═══════════════════════════════════════════════════════════
// 第 1 层：项目默认配置（写死在这里，命令改不了）
// ═══════════════════════════════════════════════════════════

export function 第一层默认配置(项目名: string): 项目配置 {
  return {
    格式版本: 1,
    项目名,
    蓝图: { 默认名: '主蓝图', 文件: '{名}.json' },
    方法: { 文件: '{名}.方法.ts', 历史个数: 10 },
    方法历史: { 文件: '{名}.方法历史.ts' },
    // 单元数 200（2026-11-22 定）：文件要能一次性读、一次性生成，
    // 预算 = min(输入 1M, 输出 256K) 的一半 = 128K token；单个单元约 149 字符 + 描述，
    // 200 个单元配 500 字描述约 118K token（压线），配 300 字描述约 82K token。0 = 不限
    限制: { 单元数: 200, token: 300000 },
  }
}

// ═══════════════════════════════════════════════════════════
// 第 2 层：用户全局配置（还没做，先返回空）
// ═══════════════════════════════════════════════════════════

function 第二层全局配置(): Partial<项目配置> {
  // TODO 以后从这里读（用户目录下的一份 json）
  return {}
}

// ═══════════════════════════════════════════════════════════
// 第 3 层：项目设置（项目里的 flow.json）
// ═══════════════════════════════════════════════════════════

export function 第三层项目配置(项目目录: string): Partial<项目配置> {
  const p = 配置路径(项目目录)
  if (!fs.existsSync(p)) return {}
  try {
    return JSON.parse(fs.readFileSync(p, 'utf8')) as Partial<项目配置>
  } catch {
    return {}
  }
}

// ═══════════════════════════════════════════════════════════
// 合并
// ═══════════════════════════════════════════════════════════

function 深合并(底: 项目配置, 覆盖: Partial<项目配置>): 项目配置 {
  const 出: 项目配置 = { ...底 }
  if (typeof 覆盖.格式版本 === 'number') 出.格式版本 = 覆盖.格式版本
  if (typeof 覆盖.项目名 === 'string') 出.项目名 = 覆盖.项目名
  for (const 段 of ['蓝图', '方法', '方法历史'] as const) {
    const v = 覆盖[段]
    if (v && typeof v === 'object') {
      if (typeof (v as 产物配置).文件 === 'string') 出[段].文件 = (v as 产物配置).文件
      if (段 === '蓝图' && typeof (v as { 默认名?: unknown }).默认名 === 'string') {
        出.蓝图.默认名 = (v as { 默认名: string }).默认名
      }
      if (段 === '方法' && typeof (v as { 历史个数?: unknown }).历史个数 === 'number') {
        出.方法.历史个数 = (v as { 历史个数: number }).历史个数
      }
    }
  }
  if (覆盖.限制 && typeof 覆盖.限制 === 'object') {
    const v = 覆盖.限制 as Partial<限制配置>
    if (typeof v.单元数 === 'number') 出.限制.单元数 = v.单元数
    if (typeof v.token === 'number') 出.限制.token = v.token
  }
  return 出
}

/** 三层合起来，得到真正生效的配置 */
export function 生效配置(项目名: string, 项目目录?: string): 项目配置 {
  let 配置 = 第一层默认配置(项目名)
  配置 = 深合并(配置, 第二层全局配置())
  if (项目目录) 配置 = 深合并(配置, 第三层项目配置(项目目录))
  return 配置
}

// ═══════════════════════════════════════════════════════════
// 工具
// ═══════════════════════════════════════════════════════════

export function 渲染模板(模板: string, 变量: Record<string, string>): string {
  // ⚠️ 不能用 \w —— 它只认 [A-Za-z0-9_]，中文的 {名} 会原样留下来
  return 模板.replace(/\{([^{}]+)\}/g, (m, k: string) => (k in 变量 ? 变量[k]! : m))
}

export function 配置路径(项目目录: string): string {
  return path.join(项目目录, 配置文件名)
}

export function 写配置(项目目录: string, 配置: 项目配置): void {
  fs.writeFileSync(配置路径(项目目录), JSON.stringify(配置, null, 2) + '\n', 'utf8')
}

/** 按配置算出某个蓝图的三件产物的文件名 */
export function 产物文件名(
  配置: 项目配置,
  蓝图名: string,
): { 蓝图: string; 方法: string; 方法历史: string } {
  const 变量 = { 名: 蓝图名, 项目: 配置.项目名 }
  return {
    蓝图: 渲染模板(配置.蓝图.文件, 变量),
    方法: 渲染模板(配置.方法.文件, 变量),
    方法历史: 渲染模板(配置.方法历史.文件, 变量),
  }
}
