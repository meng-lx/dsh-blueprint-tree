import { test } from 'node:test'
import assert from 'node:assert/strict'
import { 跑 } from '../src/状态机.ts'
import type { 引擎选项 } from '../src/状态机.ts'
import type { 蓝图, 单元 } from '../src/commands/unit-add.ts'

function 造图(名: string, 单元们: Partial<单元>[], 开始?: string): 蓝图 {
  return {
    格式版本: 1,
    名,
    开始: 开始 ?? '开始',
    结束: '结束',
    同步性: 0,
    单元: 单元们.map((u) => ({ 类型: '硬', 标签: '无', 状态: '提醒', ...u, 名: u.名! })) as 单元[],
  }
}

function 引擎(图们: Record<string, 蓝图>, 方法: 引擎选项['方法'] = {}): 引擎选项 {
  return { 读蓝图: (名) => 图们[名], 蓝图名们: () => Object.keys(图们), 方法, 共享数据: {}, 主蓝图名: '主蓝图' }
}

test('退两层后进兄弟子图：来源是父图格子，数据不串同名诱饵', async () => {
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['外图'] },
    { 名: '外图', 类型: '子蓝图', 下层: ['后图'] },
    { 名: '后图', 类型: '子蓝图', 下层: ['结束'] },
    { 名: '结束', 类型: '结束', 下层: ['$结束'] },
  ])
  const 外 = 造图('外图', [
    { 名: '外入口', 类型: '软', 下层: ['内图'] },
    { 名: '内图', 类型: '子蓝图', 下层: ['$结束'] },
  ], '外入口')
  const 内 = 造图('内图', [{ 名: '内出口', 类型: '软', 下层: ['$结束'] }], '内出口')
  const 后 = 造图('后图', [{ 名: '后入口', 类型: '软', 下层: ['$结束'] }], '后入口')

  let 收到: { 来源: string; 数据: Record<string, unknown> }[] = []
  const 选项 = 引擎({ 主蓝图: 主, 外图: 外, 内图: 内, 后图: 后 }, {
    内出口: () => ({ x: 42 }),
    后入口: (输入) => { 收到 = 输入; return {} },
  })
  // 后图里放一份同名数据当诱饵：按名字扫会先撞上它
  选项.共享数据['后图'] = { 外图: { x: 99 } }

  const 结果 = await 跑(主, 选项)
  assert.equal(结果.结局, '完成')
  assert.equal(收到.length, 1)
  assert.equal(收到[0].来源, '外图')
  assert.deepEqual(收到[0].数据, { x: 42 })
  assert.deepEqual(选项.共享数据['主蓝图']?.外图, { x: 42 })
})

test('广播只读隔离：普通边改嵌套值，广播读者仍看到原值', async () => {
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['发布'] },
    { 名: '发布', 类型: '硬', 标签: '广播', 下层: ['处理'] },
    { 名: '处理', 类型: '硬', 下层: ['观察'] },
    { 名: '观察', 类型: '硬', 下层: ['结束'] },
    { 名: '结束', 类型: '结束', 下层: ['$结束'] },
  ])
  let 观察到的广播: Record<string, unknown> | undefined
  const 选项 = 引擎({ 主蓝图: 主 }, {
    发布: () => ({ nested: { n: 1 } }),
    处理: (输入) => {
      const 广播 = 输入.find((i) => i.来源 === '__广播')
      const 普通 = 输入.find((i) => i.来源 === '发布')
      if (广播) (广播.数据 as any).发布.nested.n = 2
      if (普通) (普通.数据 as any).nested.n = 3
      return {}
    },
    观察: (输入) => {
      观察到的广播 = 输入.find((i) => i.来源 === '__广播')?.数据
      return {}
    },
  })

  const 结果 = await 跑(主, 选项)
  assert.equal(结果.结局, '完成')
  assert.deepEqual(观察到的广播, { 发布: { nested: { n: 1 } } })
  assert.deepEqual((选项.共享数据 as any).__广播, { 发布: { nested: { n: 1 } } })
})
