// 硬目标「两个来源各来两次」的配对（测评第 5 条验收序列）
//
// A₁ → A₂ → B₁ → B₂，H 只该消费 (A₁,B₁) 与 (A₂,B₂)：
//   · A₁ 收下（还缺 B）
//   · A₂ 这时 H 还缺 B，但 A 这一路已交过 ⇒ 暂存待重试
//   · B₁ 收下 ⇒ H 齐活，(A₁,B₁) 被取走
//   · H 跑完 ⇒ 重试把 A₂ 那条建出来（还缺 B₂）
//   · B₂ 到达 ⇒ 补进去 ⇒ (A₂,B₂)

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { 待做池 } from '../src/待做池.ts'
import type { 待做项 } from '../src/待做池.ts'

function 项(补: Partial<待做项> = {}): 待做项 {
  return {
    蓝图: '主蓝图',
    单元: 'H',
    还差: [
      { 蓝图: '主蓝图', 单元: 'A' },
      { 蓝图: '主蓝图', 单元: 'B' },
    ],
    标签: null,
    时间戳: 0,
    符号: null,
    携带: [],
    ...补,
  }
}

test('A₁→A₂→B₁→B₂：只消费 (A₁,B₁) 与 (A₂,B₂)', () => {
  const 池 = new 待做池()

  // A₁
  池.录入(项({ 携带: [{ 来源: 'A', 数据: { n: 1 } }] }))
  池.到一次('主蓝图', 'H', { 蓝图: '主蓝图', 单元: 'A' })
  // A₂：A 这一路已经交过 ⇒ 暂不接收
  const 挂起 = 池.录入(项({ 携带: [{ 来源: 'A', 数据: { n: 2 } }] }))
  assert.ok(挂起 instanceof Promise, '重复到达的那一路要挂着等')
  assert.equal(池.待交付数, 1, '暂存一份')
  // B₁
  池.录入(项({ 携带: [{ 来源: 'B', 数据: { n: 1 } }] }))
  池.到一次('主蓝图', 'H', { 蓝图: '主蓝图', 单元: 'B' })

  const 第一轮 = 池.取()!
  assert.deepEqual(
    第一轮.携带?.map((x) => [x.来源, (x.数据 as { n: number }).n]).sort(),
    [
      ['A', 1],
      ['B', 1],
    ],
    '第一轮只该消费 (A₁,B₁)',
  )

  // 跑完 ⇒ 重试把 A₂ 建出来
  池.完成(第一轮)
  assert.equal(池.长度, 1, '重试之后池里应有一条新的 H')
  assert.equal(池.待交付数, 0, '暂存的那份已经建出来了')
  const 第二轮候选 = 池.全部()[0]!
  assert.deepEqual(第二轮候选.携带?.map((x) => x.来源), ['A'], '新的那条只带 A₂')
  assert.deepEqual(第二轮候选.还差.map((x) => x.单元), ['B'], '只还缺 B')

  // B₂
  池.录入(项({ 携带: [{ 来源: 'B', 数据: { n: 2 } }] }))
  池.到一次('主蓝图', 'H', { 蓝图: '主蓝图', 单元: 'B' })
  const 第二轮 = 池.取()!
  assert.deepEqual(
    第二轮.携带?.map((x) => [x.来源, (x.数据 as { n: number }).n]).sort(),
    [
      ['A', 2],
      ['B', 2],
    ],
    '第二轮只该消费 (A₂,B₂)',
  )
  assert.equal(池.长度, 1, '没有多出来的重复待办')
  assert.equal(池.丢弃数, 0, '一次都没丢')
})
