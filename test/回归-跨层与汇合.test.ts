// 跨层与汇合回归（对方模型第二轮复核 2026-11-25）：
//   ① 普通支路 + 子图同汇一个硬单元 ⇒ 子图先/后完成不能影响结局（旧实现依赖完成顺序）
//   ② 连续退出两层子图 ⇒ 最外层消费者拿到的来源应是它自己的直接上游格子，数据也要在

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { 跑 } from '../src/状态机.ts'
import type { 引擎选项 } from '../src/状态机.ts'
import type { 蓝图, 单元 } from '../src/commands/unit-add.ts'

function 造图(名: string, 单元们: Partial<单元>[], 开始?: string): 蓝图 {
  return {
    格式版本: 1,
    名,
    开始: 开始 ?? '开始',
    结束: '结束',
    同步性: 0,
    单元: 单元们.map((u) => ({
      类型: '硬',
      标签: '无',
      状态: '提醒',
      ...u,
      名: u.名!,
    })) as 单元[],
  }
}

function 引擎(图们: Record<string, 蓝图>, 方法: 引擎选项['方法'] = {}): 引擎选项 {
  return {
    读蓝图: (名) => 图们[名],
    蓝图名们: () => Object.keys(图们),
    方法,
    共享数据: {},
    主蓝图名: '主蓝图',
  }
}

const 等 = (毫秒: number) => new Promise<void>((好) => setTimeout(好, 毫秒))

function 汇合图() {
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['普通', '子'] },
    { 名: '普通', 类型: '软', 下层: ['汇总'] },
    { 名: '子', 类型: '子蓝图', 下层: ['汇总'] },
    { 名: '汇总', 类型: '硬', 下层: ['结束'] },
    { 名: '结束', 类型: '结束', 下层: ['$结束'] },
  ])
  const 子 = 造图('子', [{ 名: '子入口', 类型: '软', 下层: ['$结束'] }], '子入口')
  return { 主, 子 }
}

for (const [普通延迟, 子延迟, 说明] of [
  [0, 25, '普通先完成'],
  [25, 0, '子图先完成'],
] as const) {
  test(`子图汇入硬单元：${说明}也要完成`, async () => {
    const { 主, 子 } = 汇合图()
    const 汇总输入: string[] = []
    const 选项 = 引擎({ 主蓝图: 主, 子 }, {
      普通: async () => {
        await 等(普通延迟)
        return { a: 1 }
      },
      子入口: async () => {
        await 等(子延迟)
        return { b: 2 }
      },
      汇总: (输入) => {
        汇总输入.push(...输入.map((i) => i.来源))
        return {}
      },
    })

    const r = await 跑(主, 选项)
    assert.equal(r.结局, '完成', JSON.stringify(r))
    assert.deepEqual(汇总输入.sort(), ['子', '普通'].sort(), '硬汇总该拿到两路的数据，来源是格子名')
  })
}

test('连续退出两层子图：最外层消费者拿到直接上游格子的数据与来源', async () => {
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['外图'] },
    { 名: '外图', 类型: '子蓝图', 下层: ['读'] },
    { 名: '读', 类型: '硬', 下层: ['结束'] },
    { 名: '结束', 类型: '结束', 下层: ['$结束'] },
  ])
  // 子蓝图单元名 = 蓝图名（引擎靠这个名字找「谁是我的父格子」）
  // 外图自己也要有一个 开始 单元 —— 否则 内图 会被当成「外图的终点」而不是入口
  const 外 = 造图('外图', [
    { 名: '开始', 类型: '开始', 下层: ['内图'] },
    { 名: '内图', 类型: '子蓝图', 下层: ['$结束'] },
  ], '开始')
  const 内 = 造图('内图', [{ 名: '内入口', 类型: '硬', 下层: ['$结束'] }], '内入口')

  let 读来源: string | undefined
  let 读数据: Record<string, unknown> | undefined
  const 选项 = 引擎({ 主蓝图: 主, 外图: 外, 内图: 内 }, {
    内入口: () => ({ result: 42 }),
    读: (输入) => {
      读来源 = 输入[0]?.来源
      读数据 = 输入[0]?.数据 as Record<string, unknown>
      return {}
    },
  })

  const r = await 跑(主, 选项)
  assert.equal(r.结局, '完成', JSON.stringify(r))
  assert.equal(读来源, '外图', '读 的直接上游是主图的 外图，不是内图的 内入口')
  assert.deepEqual(读数据, { result: 42 }, '内层的出口输出要逐层提交到最外层格子')
})
