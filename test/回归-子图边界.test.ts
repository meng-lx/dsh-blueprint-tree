// 子图边界回归（首轮测评第二轮 2026-11-25，对方模型复核提出的点）：
// 父图里那张「子蓝图格子」应该只拿到**出口**的输出，不是子图里跑过的每个单元的字段合集。

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { 跑 } from '../src/状态机.ts'
import type { 引擎选项 } from '../src/状态机.ts'
import type { 蓝图, 单元 } from '../src/commands/unit-add.ts'

function 造图(名: string, 单元们: Partial<单元>[], 开始?: string): 蓝图 {
  return {
    格式版本: 1,
    名,
    开始: 开始 ?? '开始',
    结束: '结束',
    同步性: 0,
    单元: 单元们.map((u) => ({
      类型: '硬',
      标签: '无',
      状态: '提醒',
      ...u,
      名: u.名!,
    })) as 单元[],
  }
}

function 引擎(图们: Record<string, 蓝图>, 方法: 引擎选项['方法'] = {}): 引擎选项 {
  return {
    读蓝图: (名) => 图们[名],
    方法,
    共享数据: {},
    主蓝图名: '主蓝图',
  }
}

test('子图边界：父图只看到出口的输出，中间单元的字段不泄漏', async () => {
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['子'] },
    { 名: '子', 类型: '子蓝图', 下层: ['看'] },
    { 名: '看', 类型: '硬', 下层: ['结束'] },
    { 名: '结束', 类型: '结束', 下层: ['$结束'] },
  ])
  const 子 = 造图(
    '子',
    [
      { 名: '子入口', 类型: '硬', 下层: ['子末'] },
      { 名: '子末', 类型: '硬', 下层: ['$结束'] },
    ],
    '子入口',
  )

  let 看到: Record<string, unknown> | undefined
  const 选项 = 引擎({ 主蓝图: 主, 子 }, {
    子入口: () => ({ 临时值: 1, 共同: '中' }),
    子末: () => ({ 结果: 2, 共同: '出' }),
    看: (输入) => {
      看到 = 输入[0]?.数据 as Record<string, unknown>
      return {}
    },
  })

  const r = await 跑(主, 选项)
  assert.equal(r.结局, '完成', JSON.stringify(r))
  assert.deepEqual(
    Object.keys(看到 ?? {}).sort(),
    ['共同', '结果'],
    '父图那张子蓝图格子只该有出口的字段，不该带上子图中间单元的 临时值',
  )
  assert.equal((看到 as Record<string, unknown> | undefined)?.共同, '出', '同名字段以出口为准')
})

test('子图边界：循环重入时，上一轮的字段不会残留在父图格子里', async () => {
  // 主蓝图：开始 → 子 → 看 → 循环1（回边，再进子）→ 子
  //   子图出口第一轮给 { 结果: 1 }，第二轮只给 { 另一个: 2 }
  //   第二轮父图读者不该再看到 结果
  let 轮 = 0
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['子'] },
    { 名: '子', 类型: '子蓝图', 下层: ['看'] },
    { 名: '看', 类型: '选择', 下层: ['循环1', '$结束'] },
    { 名: '循环1', 类型: '循环向量', 下层: ['子'] },
  ])
  const 子 = 造图(
    '子',
    [
      { 名: '子入口', 类型: '硬', 下层: ['子末'] },
      { 名: '子末', 类型: '硬', 下层: ['$结束'] },
    ],
    '子入口',
  )

  const 每轮看到: string[][] = []
  const 选项 = 引擎({ 主蓝图: 主, 子 }, {
    子入口: () => ({ 中间: 轮 }),
    子末: () => {
      轮 += 1
      return 轮 === 1 ? { 结果: 1 } : { 另一个: 2 }
    },
    看: (输入) => {
      每轮看到.push(Object.keys((输入[0]?.数据 ?? {}) as Record<string, unknown>).sort())
      return 轮 === 1 ? { Start_循环1: true } : { Start_$结束: true }
    },
  })

  const r = await 跑(主, 选项)
  assert.equal(r.结局, '完成', JSON.stringify(r))
  assert.equal(每轮看到.length, 2, `看 该跑两轮，实际 ${每轮看到.length}`)
  assert.deepEqual(每轮看到[0], ['结果'], '第一轮只该有出口字段')
  assert.deepEqual(每轮看到[1], ['另一个'], '第二轮不该残留上一轮的 结果')
})

test('子图边界：父图消费方拿到的「来源」是子蓝图格子名，不是子图内层单元名', async () => {
  // 首轮测评第二轮补的坑：父图那个格子的 来源 曾经写成子图最后一个单元（子末），
  // 于是 method.brief 里看到的上游名字、以及按名取包的代码全对不上。
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['子'] },
    { 名: '子', 类型: '子蓝图', 下层: ['看'] },
    { 名: '看', 类型: '硬', 下层: ['结束'] },
    { 名: '结束', 类型: '结束', 下层: ['$结束'] },
  ])
  const 子 = 造图(
    '子',
    [
      { 名: '子入口', 类型: '硬', 下层: ['子末'] },
      { 名: '子末', 类型: '硬', 下层: ['$结束'] },
    ],
    '子入口',
  )

  let 看来源: string | undefined
  let 子末来源: string | undefined
  const 选项 = 引擎({ 主蓝图: 主, 子 }, {
    子入口: () => ({ a: 1 }),
    子末: (输入) => {
      子末来源 = 输入[0]?.来源
      return { b: 2 }
    },
    看: (输入) => {
      看来源 = 输入[0]?.来源
      return {}
    },
  })

  const r = await 跑(主, 选项)
  assert.equal(r.结局, '完成', JSON.stringify(r))
  assert.equal(子末来源, '子入口', '子图内部照旧：来源 = 刚刚跑完的那个单元名')
  assert.equal(看来源, '子', '跨出子图：来源 = 父图那个子蓝图格子的名字')
})
