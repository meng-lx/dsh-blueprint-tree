async function 新项目(): Promise<string> {
  const 父 = fs.mkdtempSync(path.join(os.tmpdir(), 'blueprint-tree-dom-'))
  const r = await 执行({ cmd: '创建项目', 参数: { 锚点: false, 路径: 父, 名: '支配' } })
  assert.equal(r.ok, true, JSON.stringify(r))
  return (r.数据 as { 项目: string }).项目
}

async function 检测(项目: string, 范围?: string): Promise<any> {
  const r = await 执行({
    cmd: '检测蓝图',
    参数: { 项目, ...(范围 ? { 范围 } : {}) },
  })
  return r
}

/** 造一张干净的链：开始 → …中间… → 结束，中间随便接 */
function 链(...中间: string[]) {
  const 单元: any[] = [{ 名: '开始', 类型: '开始', 标签: '无', 状态: '正常', 下层: [中间[0] ?? '结束'] }]
  for (let i = 0; i < 中间.length; i++) {
    const 下 = i + 1 < 中间.length ? [中间[i + 1]] : ['结束']
    单元.push({ 名: 中间[i], 类型: '硬', 标签: '无', 状态: '正常', 下层: 下 })
  }
  单元.push({ 名: '结束', 类型: '结束', 标签: '无', 状态: '正常', 下层: ['$结束'] })
  return { 格式版本: 1, 名: '主蓝图', 开始: '开始', 结束: '结束', 同步性: 0, 单元 }
}

