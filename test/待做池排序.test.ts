// 待做池的取项顺序（测评第 5 条：背压与排序）
//
// 口径（交接 2026-11-25 ·「背压与排序」验收）：
//   ① 循环项（⟳）最优先；
//   ② 同类按较早时间戳（并发轮次）；
//   ③ 时间戳相同时按入池顺序；
// 且「未就绪的循环项」不许挡住普通项。

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { 待做池, 循环符号 } from '../src/待做池.ts'
import type { 待做项, 单元标识 } from '../src/待做池.ts'

const 甲: 单元标识 = { 蓝图: '主蓝图', 单元: '甲' }

function 项(名: string, 补: Partial<待做项> = {}): 待做项 {
  return { 蓝图: '主蓝图', 单元: 名, 还差: [], 标签: null, 时间戳: 0, 符号: null, ...补 }
}

test('循环项优先于普通项（哪怕普通项先入池）', () => {
  const 池 = new 待做池()
  池.录入(项('普通'))
  池.录入(项('回边', { 符号: 循环符号, 时间戳: 1 }))

  assert.equal(池.取()?.单元, '回边', '⟳ 先取')
  assert.equal(池.取()?.单元, '普通', '⟳ 取完才给普通')
})

test('同为循环项 ⇒ 较早时间戳先', () => {
  const 池 = new 待做池()
  池.录入(项('回边后', { 符号: 循环符号, 时间戳: 2 }))
  池.录入(项('回边前', { 符号: 循环符号, 时间戳: 1 }))

  assert.equal(池.取()?.单元, '回边前')
  assert.equal(池.取()?.单元, '回边后')
})

test('时间戳相同 ⇒ 按入池顺序', () => {
  const 池 = new 待做池()
  池.录入(项('一'))
  池.录入(项('二'))
  池.录入(项('三'))

  assert.equal(池.取()?.单元, '一')
  assert.equal(池.取()?.单元, '二')
  assert.equal(池.取()?.单元, '三')
})

test('未就绪的循环项不挡普通项', () => {
  const 池 = new 待做池()
  // ⟳ 还差「甲」没到 ⇒ 不可执行
  池.录入(项('回边', { 符号: 循环符号, 还差: [甲] }))
  池.录入(项('普通'))

  assert.equal(池.取()?.单元, '普通', '循环项没就绪时要先给普通项')
})

test('等格子的项不参与取，也不排在最前', () => {
  const 池 = new 待做池()
  池.录入(项('等子图', { 等格子: '子' }))
  池.录入(项('普通'))

  assert.equal(池.取()?.单元, '普通')
  assert.equal(池.取(), undefined, '等格子的仍然取不到')
})
