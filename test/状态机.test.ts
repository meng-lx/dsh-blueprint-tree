test('循环向量：⟳ 那条能进池，且优先于正常那条被取', async () => {
  // 开始 → 甲 → 循环1（循环向量）→ 甲
  //   甲 第一次跑完给循环1，循环1 展开成「甲 + ⟳」进池
  //   甲 第二次跑（⟳ 那条），这次不再下发了
  let 次 = 0
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['甲'] },
    { 名: '甲', 类型: '硬', 下层: ['循环1'] },
    { 名: '循环1', 类型: '循环向量', 下层: ['甲'] },
  ])

  const 选项 = 引擎({ 主蓝图: 主 }, {
    甲: () => {
      次 += 1
      return 次 === 1 ? { Start_循环1: true, 第: 1 } : { 第: 2 }
    },
  })

  const r = await 跑(主, 选项)
  assert.equal(r.结局, '完成', JSON.stringify(r))
  assert.equal(次, 2, `甲 该跑 2 次（正常 + ⟳），实际 ${次}`)
})

