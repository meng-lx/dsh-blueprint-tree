// 状态机的最小测试 —— 只跑内存里的图，不碰磁盘、不碰项目登记表。

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { 跑 } from '../src/状态机.ts'
import type { 引擎选项 } from '../src/状态机.ts'
import type { 蓝图, 单元 } from '../src/commands/unit-add.ts'

/** 造一张图 */
function 造图(名: string, 单元们: Partial<单元>[], 开始?: string): 蓝图 {
  return {
    格式版本: 1,
    名,
    开始: 开始 ?? '开始',
    结束: '结束',
    同步性: 0,
    单元: 单元们.map((u) => ({
      类型: '硬',
      标签: '无',
      状态: '提醒',
      ...u,
      名: u.名!,
    })) as 单元[],
  }
}

/** 只读内存的引擎 */
function 引擎(图们: Record<string, 蓝图>, 方法: 引擎选项['方法'] = {}): 引擎选项 {
  return {
    读蓝图: (名) => 图们[名],
    方法,
    共享数据: {},
    主蓝图名: '主蓝图',
  }
}

test('最小链：开始 → 硬 → 结束', async () => {
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['甲'] },
    { 名: '甲', 类型: '硬', 下层: ['结束'] },
    { 名: '结束', 类型: '结束', 下层: ['$结束'] },
  ])
  const 选项 = 引擎({ 主蓝图: 主 }, {
    甲: () => ({ 结果: 1 }),
  })

  const r = await 跑(主, 选项)
  assert.equal(r.结局, '完成', JSON.stringify(r))
  assert.deepEqual(r.跑了, ['开始', '甲', '结束'])
  assert.deepEqual(选项.共享数据['主蓝图']['甲'], { 结果: 1 })
})

test('硬单元等齐上游才跑', async () => {
  // 开始 → 甲 → 乙
  //    ↘ 丙 → 丁（丁要等乙、丙都到）
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['甲', '丙'] },
    { 名: '甲', 类型: '硬', 下层: ['乙'] },
    { 名: '丙', 类型: '硬', 下层: ['丁'] },
    { 名: '乙', 类型: '硬', 下层: ['丁'] },
    { 名: '丁', 类型: '硬', 下层: ['结束'] },
    { 名: '结束', 类型: '结束', 下层: ['$结束'] },
  ])

  const 顺序: string[] = []
  const 选项 = 引擎({ 主蓝图: 主 }, {
    甲: () => { 顺序.push('甲'); return {} },
    丙: () => { 顺序.push('丙'); return {} },
    乙: () => { 顺序.push('乙'); return {} },
    丁: () => { 顺序.push('丁'); return {} },
  })

  const r = await 跑(主, 选项)
  assert.equal(r.结局, '完成', JSON.stringify(r))
  assert.equal(顺序[顺序.length - 1], '丁', '丁必须最后跑（等齐乙、丙）')
})

test('选择单元：Start_X 为 false 的下游不跑', async () => {
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['选'] },
    { 名: '选', 类型: '选择', 下层: ['甲', '乙'] },
    { 名: '甲', 类型: '硬', 下层: ['汇'] },
    { 名: '乙', 类型: '硬', 下层: ['汇'] },
    // 分支汇合点必须是「软」：只走一条分支，另一条根本不会到
    { 名: '汇', 类型: '软', 下层: ['结束'] },
    { 名: '结束', 类型: '结束', 下层: ['$结束'] },
  ])

  const 跑了: string[] = []
  const 选项 = 引擎({ 主蓝图: 主 }, {
    选: () => {
      跑了.push('选')
      return { Start_甲: true, Start_乙: false }
    },
    甲: () => { 跑了.push('甲'); return {} },
    乙: () => { 跑了.push('乙'); return {} },
  })

  const r = await 跑(主, 选项)
  assert.equal(r.结局, '完成', JSON.stringify(r))
  assert.deepEqual(跑了, ['选', '甲'], '乙 的 Start_ 是 false，不该跑')
})

