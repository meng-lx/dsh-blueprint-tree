test('软单元：不等齐上游，来一个就跑', async () => {
  // 开始 → 甲、乙 都连汇
  //   甲 秒回，乙 慢 50ms
  //   汇 是软 ⇒ 还差 [] ⇒ 甲一到就能跑，不用等乙
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['甲', '乙'] },
    { 名: '甲', 类型: '硬', 下层: ['汇'] },
    { 名: '乙', 类型: '硬', 下层: ['汇'] },
    { 名: '汇', 类型: '软', 下层: ['结束'] },
    { 名: '结束', 类型: '结束', 下层: ['$结束'] },
  ])

  const 顺序: string[] = []
  const 选项 = 引擎({ 主蓝图: 主 }, {
    甲: () => { 顺序.push('甲'); return {} },
    乙: async () => {
      await new Promise((r) => setTimeout(r, 50))
      顺序.push('乙')
      return {}
    },
    汇: () => { 顺序.push('汇'); return {} },
  })

  const r = await 跑(主, 选项)
  assert.equal(r.结局, '完成', JSON.stringify(r))
  // 汇 是软 ⇒ 甲一到就跑，没等乙；乙 慢 50ms，但已经在跑了，
  // 结束信号到了也要等它收尾（用户 m04327：在跑的要等）
  assert.ok(顺序.includes('汇'), `汇 必须跑过，实际：${顺序.join(',')}`)
  assert.ok(
    顺序.indexOf('汇') < 顺序.indexOf('乙'),
    `汇 该比乙先跑（软单元不等齐上游），实际：${顺序.join(',')}`,
  )
})

