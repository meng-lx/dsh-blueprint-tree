test('卡死：池里的单元等一个永远不会跑的上游', async () => {
  // 甲 连 乙；但 乙 还有一个上层「丙」，而 丙 从「开始」走不到 ⇒ 永远不会跑
  // ⇒ 乙 录进池后，还差里留着「丙」，永远删不掉 ⇒ 卡死
  const 主 = 造图('主蓝图', [
    { 名: '开始', 类型: '开始', 下层: ['甲'] },
    { 名: '甲', 类型: '硬', 下层: ['乙'] },
    { 名: '乙', 类型: '硬', 下层: [] },
    { 名: '丙', 类型: '硬', 下层: ['乙'] },
  ])

  const r = await 跑(主, 引擎({ 主蓝图: 主 }, { 甲: () => ({}), 乙: () => ({}), 丙: () => ({}) }))
  assert.equal(r.结局, '卡死', JSON.stringify(r))
  assert.equal(r.剩下.length, 1)
  assert.equal(r.剩下[0].单元, '乙')
})
